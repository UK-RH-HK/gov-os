"""``gov update <version>`` (W2-17, DAEO-sdhj; CAP-45.a, W2-M176): an adopted project moves to release B without
re-adopting.

Steps, in order (the interface of ``e2/gov-update``):

1. The lock names release A (``governance/framework.lock``, not ``release: null``); A is not B; the tree is clean
   (``--check`` reports the uncommitted paths and goes on).
2. Release B verified in the source (``--source``, else ``_src_path``) from git objects at its tag: the manifest, every
   file under ``template/``, the wheel (built as ``gov release`` builds it, or ``--wheel``); the tag ``vA`` exists.
3. The plan: release A and release B rendered by ``copier copy --skip-tasks`` into temporary folders; every path of
   either render compared three ways (``classify``). ``--check`` stops here and writes nothing.
4. The point recorded (HEAD, the pin's link and record); B's gov installed as the pin (``gov.install.pin.place``); the
   plan applied; ``.copier-answers.yml`` from B's render and the lock with B's manifest; the adapters regenerated by the
   pinned gov; the overlay, the lock's drift and the pinned gov's version checked; one commit with the record
   ``governance/updates/<B>.json``. Any failure rolls back to the point (``UpdateFailed``, naming the step).
5. The memory store refreshed by the pinned gov (``gov rebuild``); a failure leaves the update committed
   (``StoreFailed``).

The settings step (W2-208, DEC-1217 (6)), inside step 4 after the regeneration: the lines an earlier release of the kit
wrote into ``.claude/settings.json`` and Emergency 2 retired (``legacy_lines``: ``Edit(.tickets/**)``, the allow
``Bash(gov launch:*)`` and ``Read(/<path>/**)`` for each path of the project's ``held-out.yaml``, read before the update
touches anything) are taken out of ``permissions.deny`` and ``permissions.allow`` by their exact text, through the
journal; the report and the record say which (``settings: {"removed": [...]}``; ``--check`` lists them too). Then the
deny and allow lines are compared with those before the update: a line gone that is neither a legacy line nor one the
old release generated is the project's own, and the update fails at the step ``settings``, naming it, and rolls back.

``rollback`` (W2-17 fix S7, DEC-1223 (6); ``gov update --rollback``): the update the lock's held release B came by is
undone in one commit: ``git revert --no-commit`` of the commit that added ``governance/updates/<B>.json`` (a conflict
with later commits stops it, nothing changed), the pin put back from the record's ``pin_before`` (a record written
before the field: the environment of the record's ``from`` release, ``no_previous_pin`` where there is none),
``governance/updates/<B>.rolled-back.json`` written, one commit; then ``gov rebuild`` with the restored pin's gov.
B's environment folder stays. A failure before the commit puts HEAD, the tree and the pin back.

The commit is made with ``--no-verify``: the project's pre-commit checks are for its agents' changes, and the update's
bytes are hash-verified and lock-checked (the ticket lead's call).
"""

from __future__ import annotations

import os
import pwd
import shutil
import stat
import subprocess
import tempfile
from pathlib import Path

from gov import lock, release
from gov.install import pin as install_pin
from gov.install.locate import common_dir, pin_root

SETTINGS = ".claude/settings.json"
PERMISSION_KINDS = ("deny", "allow")
# W2-208 (DEC-1217 (6); EMERGENCY-2 2.4): the lines earlier releases of the kit wrote, by their exact text; the Read
# deny per held-out path is added from the project's own held-out.yaml (``legacy_lines``).
LEGACY = {"deny": ("Edit(.tickets/**)",), "allow": ("Bash(gov launch:*)",)}
OUTCOMES = ("updated", "added", "removed", "merged", "kept", "conflicts", "overlay")
OVERLAY = "governance/project/"
UPDATES_REL = "governance/updates"
SOURCES = ".rulesync"


class UpdateRefused(Exception):
    """Refused before anything is written; ``reason`` names the check."""

    def __init__(self, reason: str, message: str):
        super().__init__(message)
        self.reason = reason


class UpdateFailed(Exception):
    """A step failed; ``rolled_back`` tells whether the project and the pin were put back at the recorded point."""

    def __init__(self, step: str, message: str, rolled_back: bool = True):
        super().__init__(message)
        self.step, self.rolled_back = step, rolled_back


class StoreFailed(Exception):
    """The update is applied and committed; the memory store was not refreshed."""

    def __init__(self, message: str, report: dict):
        super().__init__(message)
        self.report = report


# --------------------------------------------------------------------------
# Files: an entry is (kind, bytes, executable) with kind "file" or "link" (bytes the link's target), or None
# --------------------------------------------------------------------------

def _entry(path: Path):
    if os.path.islink(path):
        return ("link", os.readlink(path).encode(), False)
    if os.path.isfile(path):
        return ("file", path.read_bytes(), bool(os.stat(path).st_mode & stat.S_IXUSR))
    return None


def _walk(root: Path) -> list[str]:
    found = []
    for top, names, files in os.walk(root):
        names[:] = [name for name in names if not (top == str(root) and name == ".git")]
        links = [name for name in names if os.path.islink(os.path.join(top, name))]
        found.extend((Path(top) / name).relative_to(root).as_posix() for name in files + links)
    return found


def _text(entry) -> bool:
    if entry is None or entry[0] != "file" or b"\0" in entry[1]:
        return False
    try:
        entry[1].decode("utf-8")
    except UnicodeDecodeError:
        return False
    return True


def merge3(own: bytes, old: bytes, new: bytes) -> bytes | None:
    """``git merge-file`` of the project's text and release B's over release A's; ``None`` where it conflicts."""
    with tempfile.TemporaryDirectory(prefix="gov-update-merge-") as folder:
        paths = []
        for name, data in (("project", own), ("release-A", old), ("release-B", new)):
            path = Path(folder) / name
            path.write_bytes(data)
            paths.append(str(path))
        done = subprocess.run(["git", "merge-file", "-p", "--quiet", *paths], capture_output=True)
    return done.stdout if done.returncode == 0 else None


def classify(rel: str, old, own, new):
    """``(outcome, action)`` for one path: ``old`` release A's render, ``own`` the project's file, ``new`` release B's
    render. An action is ``("write", bytes, executable, link)``, ``("delete",)`` or ``("aside", bytes, executable,
    link)`` (release B's copy written under ``governance/updates/<B>/release/``)."""
    def write(kind, entry):
        return (kind, entry[1], entry[2], entry[0] == "link")
    if own == new:
        return None, None
    if rel.startswith(OVERLAY):  # the overlay is the project's: an existing file is never written
        if own is not None:
            return ("overlay", None) if new != old else (None, None)
        return "added", write("write", new)
    if own == old:
        if new is None:
            return "removed", ("delete",)
        return ("added" if old is None else "updated"), write("write", new)
    if new == old:
        return "kept", None
    if _text(own) and _text(new) and (old is None or _text(old)):
        merged = merge3(own[1], old[1] if old is not None else b"", new[1])
        if merged is not None:
            return "merged", ("write", merged, own[2], False)
    if new is None:
        return "conflicts", None
    return "conflicts", write("aside", new)


def plan(old_root: Path, project: Path, new_root: Path) -> tuple[dict, dict]:
    """``(files, actions)``: every path of either render (``.copier-answers.yml`` aside) under its outcome, and what
    applying it writes or deletes, by path."""
    files = {outcome: [] for outcome in OUTCOMES}
    actions = {}
    for rel in sorted((set(_walk(old_root)) | set(_walk(new_root))) - {lock.ANSWERS_REL}):
        outcome, action = classify(rel, _entry(old_root / rel), _entry(project / rel), _entry(new_root / rel))
        if outcome is not None:
            files[outcome].append(rel)
        if action is not None:
            actions[rel] = action
    return files, actions


class Journal:
    """Every file the update writes or deletes, with what it held before, so that ``restore`` puts it back."""

    def __init__(self, root: Path):
        self.root = Path(root)
        self.saved: dict[str, tuple | None] = {}
        self.created: list[Path] = []

    def save(self, rel: str) -> None:
        if rel in self.saved:
            return
        path = self.root / rel
        if os.path.islink(path):
            self.saved[rel] = ("link", os.readlink(path), None)
        elif os.path.isfile(path):
            self.saved[rel] = ("file", path.read_bytes(), stat.S_IMODE(os.stat(path).st_mode))
        else:
            self.saved[rel] = None

    def _folder(self, folder: Path) -> None:
        missing = []
        while not os.path.lexists(folder):
            missing.append(folder)
            folder = folder.parent
        for path in reversed(missing):
            path.mkdir()
            self.created.append(path)

    def write(self, rel: str, data: bytes, executable: bool | None = None, link: bool = False) -> None:
        self.save(rel)
        path = self.root / rel
        self._folder(path.parent)
        if link or os.path.islink(path):
            if os.path.lexists(path):
                os.unlink(path)
        if link:
            os.symlink(data.decode(), path)
            return
        path.write_bytes(data)
        if executable is not None:
            mode = stat.S_IMODE(os.stat(path).st_mode)
            os.chmod(path, mode | 0o111 if executable else mode & ~0o111)

    def delete(self, rel: str) -> None:
        self.save(rel)
        path = self.root / rel
        if os.path.lexists(path):
            os.unlink(path)
        folder = path.parent
        while folder != self.root and folder.is_dir() and not any(folder.iterdir()):
            folder.rmdir()
            folder = folder.parent

    def restore(self) -> None:
        for rel, saved in reversed(list(self.saved.items())):
            path = self.root / rel
            if os.path.lexists(path) and (saved is None or saved[0] == "link" or os.path.islink(path)):
                os.unlink(path)
            if saved is None:
                continue
            path.parent.mkdir(parents=True, exist_ok=True)
            if saved[0] == "link":
                os.symlink(saved[1], path)
            else:
                path.write_bytes(saved[1])
                os.chmod(path, saved[2])
        for folder in reversed(self.created):
            try:
                folder.rmdir()
            except OSError:
                pass


