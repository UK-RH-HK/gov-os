# The settings step (W2-208)
# --------------------------------------------------------------------------

def legacy_lines(project: Path) -> dict[str, list[str]]:
    """The deny and allow lines earlier releases of the kit wrote and Emergency 2 retired, by their exact text: the
    fixed ones and ``Read(/<path>/**)`` (the form the retired held-out step wrote) for each path of the project's
    ``held-out.yaml``. A held-out file that does not load adds none (``load_held_out`` refuses it elsewhere)."""
    from gov.util import heldout
    try:
        held = heldout.load_held_out(str(project))
    except heldout.HeldOutError:
        held = []
    return {"deny": [*LEGACY["deny"], *(f"Read(/{path}/**)" for path in held)], "allow": list(LEGACY["allow"])}


def permission_lines(data: bytes | None) -> dict[str, list[str]]:
    """``permissions.deny`` and ``permissions.allow`` of a settings file's bytes; a list that is not there, or a
    file that is not a JSON object, gives none."""
    import json
    try:
        value = json.loads(data.decode("utf-8")) if data is not None else {}
    except (UnicodeDecodeError, ValueError):
        value = {}
    permissions = value.get("permissions") if isinstance(value, dict) else None
    permissions = permissions if isinstance(permissions, dict) else {}
    return {kind: [line for line in permissions.get(kind) if isinstance(line, str)]
            if isinstance(permissions.get(kind), list) else [] for kind in PERMISSION_KINDS}


def _settings_bytes(project: Path) -> bytes | None:
    path = Path(project) / SETTINGS
    return path.read_bytes() if path.is_file() and not path.is_symlink() else None


def removed_lines(before: dict[str, list[str]], legacy: dict[str, list[str]]) -> list[str]:
    """The legacy lines the project's settings held before the update, deny first, each in its order there."""
    return [line for kind in PERMISSION_KINDS for line in before[kind] if line in legacy[kind]]


def remove_legacy(project: Path, legacy: dict[str, list[str]], journal: Journal) -> None:
    """``.claude/settings.json`` written through ``journal`` without the legacy lines; a list emptied by it dropped.
    Nothing is written where the file holds none of them, or is absent or not a JSON object."""
    import json
    data = _settings_bytes(project)
    try:
        value = json.loads(data.decode("utf-8")) if data is not None else None
    except (UnicodeDecodeError, ValueError):
        value = None
    permissions = value.get("permissions") if isinstance(value, dict) else None
    if not isinstance(permissions, dict):
        return
    changed = False
    for kind in PERMISSION_KINDS:
        lines = permissions.get(kind)
        if not isinstance(lines, list):
            continue
        kept = [line for line in lines if line not in legacy[kind]]
        if len(kept) != len(lines):
            changed = True
            if kept:
                permissions[kind] = kept
            else:
                del permissions[kind]
    if changed:
        journal.write(SETTINGS, (json.dumps(value, indent=2, ensure_ascii=False) + "\n").encode())


def lost_lines(before: dict[str, list[str]], after: dict[str, list[str]], legacy: dict[str, list[str]],
               generated: dict[str, list[str]]) -> list[str]:
    """The project's own lines the update lost (F2): in ``before``, not in ``after``, and neither a legacy line nor
    one the old release generated; each as ``<kind> <line>``."""
    return [f"{kind} {line}" for kind in PERMISSION_KINDS for line in before[kind]
            if line not in after[kind] and line not in legacy[kind] and line not in generated[kind]]


def _check(project: Path, files: dict, overlay: dict, drift_before: set, link: Path, cli_version: str) -> None:
    changed = sorted(rel for rel, data in overlay.items()
                     if not (project / OVERLAY / rel).is_file() or (project / OVERLAY / rel).read_bytes() != data)
    if changed:
        raise RuntimeError(f"overlay files changed by the update: {', '.join(OVERLAY + rel for rel in changed)}")
    comparison = lock.compare(project)
    if comparison.verdict not in ("MATCH", "DRIFT") or comparison.reason:
        raise RuntimeError(f"the lock does not compare: {comparison.verdict} {comparison.reason or ''}".strip())
    allowed = set(files["kept"]) | set(files["merged"]) | set(files["conflicts"]) | drift_before
    extra = sorted(set(comparison.drifted_files) - allowed)
    if extra:
        raise RuntimeError(f"the lock drifts on files the update does not report kept, merged or conflicts: "
                           f"{', '.join(extra[:20])}")
    done = _pinned(link, project, "--version")
    if done.returncode or cli_version not in done.stdout.split():
        raise RuntimeError(f"the pinned gov {link} says {done.stdout.strip() or done.stderr.strip()!r}, not "
                           f"version {cli_version}")


def update(project, version: str, check: bool = False, source=None, wheel=None) -> dict:
    """Update the adopted project at ``project`` to release ``version``; the report."""
    project = Path(os.path.abspath(os.fspath(project)))
    held = held_release(project)
    if held == version:
        raise UpdateRefused("same", f"the project is already at release {version} ({lock.LOCK_REL})")
    dirty = uncommitted(project)
    if dirty and not check:
        raise UpdateRefused("dirty", f"the tree has uncommitted changes the update could not roll back to: "
                                     f"{', '.join(dirty[:20])}; commit or remove them first")
    answers = lock._read_map(project / lock.ANSWERS_REL) or {}
    named = os.fspath(source) if source else answers.get("_src_path")
    if not isinstance(named, str) or not named:
        raise UpdateRefused("no_release", f"no source: --source is not given and {lock.ANSWERS_REL} names no "
                                          "_src_path")
    src = Path(named).expanduser()
    src = src if src.is_absolute() else project / src
    try:
        data, digest, manifest = release.verify_at(src, version, files=True)
    except release.ReleaseError as exc:
        raise UpdateRefused(exc.reason or "manifest", str(exc)) from None
    try:
        release.verify_at(src, held, files=False)
    except release.ReleaseError as exc:
        raise UpdateRefused("old_release", f"release {held}, which the project holds, cannot be read in {src}: "
                                           f"{exc}") from None
    common = common_dir(project)
    root = pin_root(common)
    with tempfile.TemporaryDirectory(prefix="gov-update-") as folder:
        scratch = Path(folder)
        (scratch / "wheel").mkdir()
        try:
            wheel_path = install_pin.wheel_for(src, version, manifest, wheel, scratch / "wheel")
        except install_pin.InstallRefused as exc:
            raise UpdateRefused("wheel", str(exc)) from None
        old_root, new_root = scratch / "A", scratch / "B"
        render(str(src) if source else named, held, old_root, project)
        render(str(src) if source else named, version, new_root, project)
        files, actions = plan(old_root, project, new_root)
        report = {"from": held, "to": version, "source": str(src), "check": check,
                  "checks": {"manifest": "passed", "files": "passed", "wheel": "passed"}, "files": files,
                  "pin": {"version": version, "environment": str(root / "envs" / version)},
                  "lock": {"version": version, "manifest_sha256": digest},
                  "adapters": "would regenerate", "store": "would refresh",
                  "settings": {"removed": removed_lines(permission_lines(_settings_bytes(project)),
                                                        legacy_lines(project))},
                  "record": f"{UPDATES_REL}/{version}.json", "commit": None}
        if check:
            if dirty:
                report["dirty"] = dirty
            return report
        return _apply(project, version, held, src, data, digest, manifest, files, actions, wheel_path, scratch,
                      common, report)


def _apply(project, version, held, src, data, digest, manifest, files, actions, wheel_path, scratch, common,
           report) -> dict:
    import json
    root = pin_root(common)
    link = root / "bin" / "gov"
    head = _git(project, "rev-parse", "HEAD").stdout.strip()
    state = _pin_state(root, version)
    drift_before = set(lock.compare(project).drifted_files)
    overlay = _overlay(project)
    legacy, before = legacy_lines(project), permission_lines(_settings_bytes(project))
    old_rules = scratch / "old-rules"
    if (project / SOURCES).is_dir():
        shutil.copytree(project / SOURCES, old_rules / SOURCES, symlinks=True)
    journal = Journal(project)
    step = "install"
    try:
        install_pin.place(common, version, wheel_path, {
            "version": version, "wheel": {"name": manifest["wheel"]["name"], "sha256": manifest["wheel"]["sha256"]},
            "manifest_sha256": digest, "source": str(src), "commit": manifest.get("commit")})
        step = "apply"
        for rel, action in actions.items():
            if action[0] == "write":
                journal.write(rel, action[1], action[2], action[3])
            elif action[0] == "delete":
                journal.delete(rel)
            else:
                journal.write(f"{UPDATES_REL}/{version}/release/{rel}", action[1], action[2], action[3])
        step = "lock"
        journal.write(lock.ANSWERS_REL, (scratch / "B" / lock.ANSWERS_REL).read_bytes())
        journal.save(lock.LOCK_REL)
        lock.write(project, release=(version, data))
        step = "adapters"
        adapters_kept, generated = _regenerate(project, old_rules, scratch / "generated-A", link, journal)
        step = "settings"
        remove_legacy(project, legacy, journal)
        lost = lost_lines(before, permission_lines(_settings_bytes(project)), legacy, generated)
        if lost:
            raise RuntimeError(f"the regenerated {SETTINGS} lost the project's own line(s), which the update may not "
                               f"take out: {', '.join(lost)}")
        step = "verify"
        _check(project, files, overlay, drift_before, link, str(manifest.get("cli_version")))
        step = "commit"
        record = {"from": held, "to": version, "source": str(src), "manifest_sha256": digest,
                  "wheel": {"name": manifest["wheel"]["name"], "sha256": manifest["wheel"]["sha256"]},
                  "files": files, "settings": report["settings"], "commit_before": head,
                  "pin_before": pin_before(state)}
        journal.write(report["record"], (json.dumps(record, indent=2) + "\n").encode())
        _git(project, "add", "-A")
        _git(project, "-c", "commit.gpgsign=false", "commit", "--no-verify", "-q", "-m",
             f"gov update: release {held} -> {version}\n\nThe project moves from release {held} to release {version} "
             f"of {src} (manifest sha256 {digest}); the record is {report['record']}.")
        commit = _git(project, "rev-parse", "HEAD").stdout.strip()
    except BaseException as exc:
        _rollback(project, head, journal, root, version, state)
        what = exc.code + ": " + exc.message if hasattr(exc, "code") and hasattr(exc, "message") else str(exc)
        raise UpdateFailed(step, f"the update to release {version} failed at the step {step} ({what}); it rolled "
                                 f"back to {head}: HEAD, the files and the pin are as before") from None
    report.update({"adapters": "regenerated", "commit": commit, "adapters_kept": adapters_kept})
    done = _pinned(link, project, "rebuild")
    if done.returncode:
        report["store"] = "failed"
        raise StoreFailed(f"the update to release {version} is applied and committed ({commit}), but the memory store "
                          f"was not refreshed ({(done.stderr or done.stdout).strip()[-500:]}): run `gov rebuild`",
                          report)
    report["store"] = "refreshed"
    return report


def _rollback(project: Path, head: str, journal: Journal, root: Path, version: str, state: dict) -> None:
    _git(project, "reset", "-q", "--hard", head, check=False)
    _git(project, "clean", "-fdq", check=False)  # the tree was clean: an untracked file is the update's
    journal.restore()
    _restore_pin(root, version, state)


