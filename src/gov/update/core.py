def _git(project: Path, *args: str, check: bool = True) -> subprocess.CompletedProcess:
    done = subprocess.run(["git", "-C", str(project), *args], capture_output=True, text=True)
    if check and done.returncode:
        raise RuntimeError(f"git {' '.join(args)}: {(done.stderr or done.stdout).strip()}")
    return done


def held_release(project: Path) -> str:
    """Release A, as the project's lock names it; refused (``not_adopted``) otherwise."""
    path = project / lock.LOCK_REL
    if not lock._present(path):
        raise UpdateRefused("not_adopted", f"{lock.LOCK_REL} is absent: the project holds no release to update from "
                                           "(adopt it with copier copy --vcs-ref v<version>)")
    data = lock._read_map(path)
    if data is None:
        raise UpdateRefused("not_adopted", f"{lock.LOCK_REL} is not a readable map: the release it holds is unknown")
    if "release" not in data:
        raise UpdateRefused("not_adopted", f"{lock.LOCK_REL} does not state the release it holds")
    entry = data["release"]
    if entry is None:
        raise UpdateRefused("not_adopted", f"{lock.LOCK_REL} states release: null: the project holds no numbered "
                                           "release to update from")
    version = entry.get("version") if isinstance(entry, dict) else None
    if not isinstance(version, str) or not version:
        raise UpdateRefused("not_adopted", f"{lock.LOCK_REL} names no release version")
    return version


def uncommitted(project: Path) -> list[str]:
    done = _git(project, "status", "--porcelain", "--untracked-files=all", check=False)
    if done.returncode:
        raise UpdateRefused("not_adopted", f"{project} is not a git repository: {done.stderr.strip()}")
    return [line[3:] for line in done.stdout.splitlines() if line.strip()]


def _clean_env() -> dict:
    return {key: value for key, value in os.environ.items()
            if key not in ("PYTHONPATH", "PYTHONHOME", "VIRTUAL_ENV", "PYTHONSAFEPATH")}


def _copier() -> str:
    found = shutil.which("copier")
    if found:
        return found
    candidate = Path(pwd.getpwuid(os.getuid()).pw_dir) / ".local" / "bin" / "copier"
    if candidate.is_file():
        return str(candidate)
    raise UpdateFailed("plan", "copier not found (PATH, ~/.local/bin): the releases cannot be rendered; nothing was "
                               "written", rolled_back=False)


def render(source: str, version: str, dest: Path, cwd: Path) -> None:
    """Release ``version`` rendered by Copier into ``dest``, its tasks skipped."""
    argv = [_copier(), "copy", "--vcs-ref", f"v{version}", "--trust", "--skip-tasks", "--defaults", "--quiet",
            source, str(dest)]
    done = subprocess.run(argv, cwd=str(cwd), capture_output=True, text=True, env=_clean_env(),
                          stdin=subprocess.DEVNULL)
    if done.returncode:
        raise UpdateFailed("plan", f"copier could not render release {version}: "
                                   f"{(done.stderr or done.stdout).strip()[-1500:]}; nothing was written",
                           rolled_back=False)


def _pin_state(root: Path, version: str) -> dict:
    link, record = root / "bin" / "gov", root / install_pin.RECORD
    return {"existed": os.path.lexists(root), "record": record.read_bytes() if record.is_file() else None,
            "link": os.readlink(link) if os.path.islink(link) else None,
            "env_existed": os.path.lexists(root / "envs" / version)}


def pin_before(state: dict) -> dict:
    """The pin as ``_pin_state`` found it, in the record's shape: ``{"existed", "link", "record"}`` (``record`` the
    ``pin.json`` parsed as JSON, ``None`` where absent or not JSON)."""
    import json
    record = None
    if state["record"] is not None:
        try:
            record = json.loads(state["record"])
        except ValueError:
            record = None
    return {"existed": state["existed"], "link": state["link"], "record": record}


def _restore_pin(root: Path, version: str, state: dict) -> None:
    if not state["existed"]:
        shutil.rmtree(root, ignore_errors=True)
        return
    link, record = root / "bin" / "gov", root / install_pin.RECORD
    if state["record"] is None:
        record.unlink(missing_ok=True)
    elif not record.is_file() or record.read_bytes() != state["record"]:
        install_pin._write_atomic(record, state["record"])
    if state["link"] is None:
        if os.path.lexists(link):
            os.unlink(link)
    elif not os.path.islink(link) or os.readlink(link) != state["link"]:
        install_pin._link(link, state["link"])
    if not state["env_existed"]:
        shutil.rmtree(root / "envs" / version, ignore_errors=True)


def _pinned(link: Path, project: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run([str(link), *args], cwd=str(project), capture_output=True, text=True, env=_clean_env(),
                          stdin=subprocess.DEVNULL)


def _overlay(project: Path) -> dict[str, bytes]:
    folder = project / OVERLAY
    return {rel: (folder / rel).read_bytes() for rel in _walk(folder) if (folder / rel).is_file()} \
        if folder.is_dir() else {}


def _regenerate(project: Path, old_root: Path, scratch: Path, link: Path, journal: Journal) -> tuple[list[str], dict]:
    """The adapters regenerated by the pinned gov, after the old release's generated output is set aside
    (``gov.adapters.merge.forget_generated``): the generated files the project changed, which are kept, and the
    deny and allow lines the old release generated (``permission_lines``)."""
    from gov.adapters import merge
    kept, previous = [], {}
    if (old_root / SOURCES).is_dir():
        scratch.mkdir()
        previous = merge.generate_into(old_root, scratch)
        kept = merge.forget_generated(project, previous, journal.write, journal.delete)
    done = _pinned(link, project, "adapters", "generate")
    if done.returncode:
        raise RuntimeError(f"{link} adapters generate ended with {done.returncode}: "
                           f"{(done.stderr or done.stdout).strip()[-1500:]}")
    return kept, permission_lines(previous.get(SETTINGS))


