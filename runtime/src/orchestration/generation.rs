/// Everything a source reads, once per reconciliation.
pub struct GenCtx<'a> {
    pub p: &'a Project,
    pub store: &'a RecordStore,
    pub cfg: Config,
    /// Ids and paths of generated/adopted tasks (findings about them never generate work).
    generated_tasks: BTreeSet<String>,
}

impl<'a> GenCtx<'a> {
    pub fn new(p: &'a Project, store: &'a RecordStore) -> Self {
        let mut generated_tasks = BTreeSet::new();
        for t in store.of_type("task") {
            if source_of(t).is_some() {
                generated_tasks.insert(t.id());
                generated_tasks.insert(t.path.clone());
            }
        }
        GenCtx {
            p,
            store,
            cfg: Config::load(p),
            generated_tasks,
        }
    }
    fn about_generated_work(&self, f: &Value) -> bool {
        let path = f["path"].as_str().unwrap_or("");
        let msg = f["message"].as_str().unwrap_or("");
        (!path.is_empty() && self.generated_tasks.contains(path))
            || self
                .generated_tasks
                .iter()
                .any(|t| t.starts_with("TASK-") && msg.contains(t.as_str()))
    }
    /// Ids of `ids` that are current governed records a `derived_from` link may name: a graph edge must reach an
    /// indexed record, so memory-quality events (never indexed, `memory::failures::MEMORY_QUALITY_DIR`) are linked
    /// the other way — the failure record's `follow_up.task` — and named in `generation.records`.
    fn linkable(&self, ids: &[String]) -> Vec<String> {
        let excluded = ["SUPERSEDED", "HISTORICAL", "REJECTED", "RETIRED", "LEGACY"];
        ids.iter()
            .filter(|i| {
                self.store
                    .get(i)
                    .map(|r| {
                        !excluded.contains(&r.status().as_str())
                            && !crate::memory::failures::is_memory_quality_path(&r.path)
                    })
                    .unwrap_or(false)
            })
            .cloned()
            .collect()
    }
}

/// **Failed tests** (Contract v3:574): a product-test family whose latest recorded run failed. The occurrence is the
/// first failing run of the current streak, so repeated failing runs are one occurrence until the family passes.
pub fn failed_tests(g: &GenCtx) -> Vec<Candidate> {
    let records = crate::verification::product::latest_records(g.p);
    // family -> (latest failing record, origin of the streak, latest entry); families whose latest run passed are done
    let mut state: BTreeMap<String, (Option<(String, String, Value)>, Option<String>, bool)> =
        BTreeMap::new();
    for r in &records {
        let rid = r["id"].as_str().unwrap_or("").to_string();
        let at = r["run_at"].as_str().unwrap_or("").to_string();
        let Some(fams) = r["families"].as_object() else {
            continue;
        };
        for (fam, e) in fams {
            let failed = e["status"].as_str() == Some("failed");
            let st = state.entry(fam.clone()).or_insert((None, None, false));
            if st.2 {
                continue; // the streak ended (an older run of the family passed, or it was decided)
            }
            match (&st.0, failed) {
                (None, true) => {
                    st.0 = Some((rid.clone(), at.clone(), e.clone()));
                    st.1 = Some(rid.clone());
                }
                (None, false) => st.2 = true,
                (Some(_), true) => st.1 = Some(rid.clone()),
                (Some(_), false) => st.2 = true,
            }
        }
    }
    let (class, _, default_paths, _) = g.cfg.source("failed-tests");
    let _ = class;
    let mut out = vec![];
    for (fam, (latest, origin, _)) in state {
        let Some((rid, at, e)) = latest else { continue };
        let origin = origin.unwrap_or_else(|| rid.clone());
        let covers: Vec<String> = e["covers"]
            .as_array()
            .map(|a| {
                a.iter()
                    .filter_map(|x| x.as_str().map(|s| s.to_string()))
                    .collect()
            })
            .unwrap_or_default();
        let paths = if covers.is_empty() || covers.iter().any(|c| c == "**") {
            default_paths.clone()
        } else {
            let mut v = covers.clone();
            v.extend(["tests/**".to_string(), "spec/**".to_string()]);
            v
        };
        out.push(Candidate {
            source: "failed-tests".into(),
            subject: fam.clone(),
            occurrence: origin.clone(),
            evidence_at: at.clone(),
            records: g.linkable(&[rid.clone()]),
            title: format!("Repair failing product test family '{fam}' ({rid})"),
            objective: format!(
                "The product test family '{fam}' fails in its latest recorded run {rid} (failing since {origin}; exit {}; command {}). Find the cause and repair the code or the test so the family passes, then record a passing run (`gov verify product`); the failing run is governed evidence, not a report claim. stderr tail: {}",
                e["exit"], e["command"], clip(e["stderr_tail"].as_str().unwrap_or(""), 400)
            ),
            paths,
            detail: json!({"family": fam, "record": rid, "streak_origin": origin, "exit": e["exit"], "command": e["command"], "covers": covers, "stdout_tail": e["stdout_tail"], "stderr_tail": e["stderr_tail"]}),
            ..Default::default()
        });
    }
    out
}

/// **Audit findings, security findings and each health failure** (Contract v3:575, :582; AC-5; O5): every check of
/// the health state (governance-suite families and doctor checks) failing at or above the policy severity, one piece
/// of remediation work per condition (a doctor check and the family reporting the same condition are one), with the
/// findings of the latest honoured governance-suite record.
pub fn health_failures(g: &GenCtx) -> Vec<Candidate> {
    let st = crate::scheduler::store::load_state(g.p);
    let Some(checks) = st["checks"].as_object() else {
        return vec![];
    };
    let threshold = crate::scheduler::catalogue::rank(&g.cfg.severity_threshold());
    let excluded = g.cfg.list("excluded_checks");
    let security = g.cfg.list("security_checks");
    let memory = g.cfg.list("memory_checks");
    // the latest honoured governance-suite record, for the findings behind each failing family
    let mut suite: Vec<&Record> = g
        .store
        .of_type("audit")
        .into_iter()
        .filter(|r| {
            r.get("scope") == "governance-suite" && crate::t2::verify_record(r).is_verified()
        })
        .collect();
    suite.sort_by_key(|r| (r.get("run_at"), r.id()));
    let latest_suite = suite.last().copied();
    // condition -> (member checks, max severity, latest at, findings)
    let mut groups: BTreeMap<String, (Vec<String>, String, String, Vec<Value>)> = BTreeMap::new();
    for (id, e) in checks {
        if e["ok"].as_bool().unwrap_or(true) || excluded.contains(id) {
            continue;
        }
        let sev = e["max_severity"].as_str().unwrap_or("none").to_string();
        if crate::scheduler::catalogue::rank(&sev) < threshold {
            continue;
        }
        let canonical = g.cfg.canonical_check(id);
        if excluded.contains(&canonical) {
            continue;
        }
        let entry = groups.entry(canonical.clone()).or_insert((
            vec![],
            "none".into(),
            String::new(),
            vec![],
        ));
        entry.0.push(id.clone());
        if crate::scheduler::catalogue::rank(&sev) > crate::scheduler::catalogue::rank(&entry.1) {
            entry.1 = sev.clone();
        }
        let at = e["at"].as_str().unwrap_or("").to_string();
        if at > entry.2 {
            entry.2 = at;
        }
        for f in e["blocking_findings"]
            .as_array()
            .cloned()
            .unwrap_or_default()
        {
            entry.3.push(f);
        }
        if let Some(s) = latest_suite {
            for f in s.data["findings"].as_array().cloned().unwrap_or_default() {
                if f["family"].as_str() == Some(id.as_str())
                    && crate::scheduler::catalogue::rank(f["severity"].as_str().unwrap_or("low"))
                        >= threshold
                {
                    entry.3.push(f);
                }
            }
        }
    }
    if groups.is_empty() {
        return vec![];
    }
    // only a failure that is still current is work: a failing result whose check inputs have changed since it was
    // recorded (the condition may have been repaired, e.g. a kernel re-verified) waits for its re-evaluation
    let stale: BTreeSet<String> = crate::scheduler::status(g.p)
        .ok()
        .and_then(|s| s["stale_checks"].as_array().cloned())
        .unwrap_or_default()
        .into_iter()
        .filter_map(|x| x.as_str().map(|s| s.to_string()))
        .collect();
    // checks whose findings name the same path report one condition (e.g. a secret in a product file reported by
    // the path-map and the secrets checks): one remediation, which remedies every one of them
    let mut conds: Vec<(String, Vec<String>, String, String, Vec<Value>)> = groups
        .into_iter()
        .map(|(c, (m, sev, at, f))| {
            let m: Vec<String> = m.into_iter().filter(|x| !stale.contains(x)).collect();
            (c, m, sev, at, f)
        })
        .filter(|(_, m, _, _, _)| !m.is_empty())
        .collect();
    let paths_of = |f: &[Value]| -> BTreeSet<String> {
        f.iter()
            .filter_map(|x| x["path"].as_str().map(|s| s.to_string()))
            .filter(|s| !s.is_empty() && !g.generated_tasks.contains(s))
            .collect()
    };
    let mut merged = true;
    while merged {
        merged = false;
        'outer: for i in 0..conds.len() {
            for j in (i + 1)..conds.len() {
                let (a, b) = (paths_of(&conds[i].4), paths_of(&conds[j].4));
                if !a.is_empty() && a.intersection(&b).next().is_some() {
                    let other = conds.remove(j);
                    let c = &mut conds[i];
                    if other.0 < c.0 {
                        c.0 = other.0.clone();
                    }
                    for m in other.1 {
                        if !c.1.contains(&m) {
                            c.1.push(m);
                        }
                    }
                    if crate::scheduler::catalogue::rank(&other.2)
                        > crate::scheduler::catalogue::rank(&c.2)
                    {
                        c.2 = other.2;
                    }
                    if other.3 > c.3 {
                        c.3 = other.3;
                    }
                    c.4.extend(other.4);
                    merged = true;
                    break 'outer;
                }
            }
        }
    }
    let markers: Vec<String> = g
        .cfg
        .list("security_markers")
        .into_iter()
        .map(|m| m.to_lowercase())
        .collect();
    let mut out = vec![];
    for (canonical, mut members, sev, at, findings) in conds {
        members.sort();
        let total = findings.len();
        let findings: Vec<Value> = findings
            .into_iter()
            .filter(|f| !g.about_generated_work(f))
            .collect();
        if total > 0 && findings.is_empty() {
            continue; // every finding is about generated work itself: no loop
        }
        let mut seen = BTreeSet::new();
        let findings: Vec<Value> = findings
            .into_iter()
            .filter(|f| seen.insert((f["message"].to_string(), f["path"].to_string())))
            .collect();
        let is_security = members
            .iter()
            .chain(std::iter::once(&canonical))
            .any(|m| security.contains(m))
            || findings.iter().any(|f| {
                let msg = f["message"].as_str().unwrap_or("").to_lowercase();
                markers.iter().any(|m| msg.contains(m.as_str()))
            });
        let is_memory = members
            .iter()
            .chain(std::iter::once(&canonical))
            .any(|m| memory.contains(m));
        let is_doctor = members.iter().all(|m| m.starts_with('D') && m.len() == 4);
        let source = if is_security {
            "security-finding"
        } else if is_memory {
            "memory-health"
        } else if is_doctor {
            "health-failure"
        } else {
            "audit-finding"
        };
        // what failed, independent of volatile counts: the finding messages and paths without digits
        let mut sig: Vec<String> = findings
            .iter()
            .map(|f| {
                format!(
                    "{}|{}",
                    f["message"]
                        .as_str()
                        .unwrap_or("")
                        .chars()
                        .filter(|c| !c.is_ascii_digit())
                        .collect::<String>(),
                    f["path"].as_str().unwrap_or("")
                )
            })
            .collect();
        sig.sort();
        sig.dedup();
        if sig.is_empty() {
            sig.push(format!("{canonical}:{sev}"));
        }
        let finding_paths: Vec<String> = findings
            .iter()
            .filter_map(|f| f["path"].as_str().map(|s| s.to_string()))
            .filter(|s| !s.is_empty())
            .collect::<BTreeSet<_>>()
            .into_iter()
            .collect();
        let (_, _, default_paths, _) = g.cfg.source(source);
        let paths = if is_security && !finding_paths.is_empty() {
            let mut v = finding_paths.clone();
            v.push("spec/**".into());
            v
        } else {
            default_paths
        };
        let msgs: Vec<String> = findings
            .iter()
            .take(5)
            .map(|f| {
                format!(
                    "{} {}{}",
                    f["severity"].as_str().unwrap_or(&sev),
                    clip(f["message"].as_str().unwrap_or(""), 200),
                    f["path"]
                        .as_str()
                        .map(|p| format!(" ({p})"))
                        .unwrap_or_default()
                )
            })
            .collect();
        let record = latest_suite
            .filter(|s| {
                s.data["findings"]
                    .as_array()
                    .map(|a| {
                        a.iter().any(|f| {
                            members
                                .iter()
                                .any(|m| f["family"].as_str() == Some(m.as_str()))
                        })
                    })
                    .unwrap_or(false)
            })
            .map(|s| s.id());
        let what = match source {
            "security-finding" => "security finding",
            "health-failure" => "health failure",
            "memory-health" => "knowledge-fabric health failure",
            _ => "audit finding",
        };
        out.push(Candidate {
            source: source.into(),
            subject: canonical.clone(),
            occurrence: digest(&sig),
            evidence_at: at.clone(),
            records: g.linkable(&record.iter().cloned().collect::<Vec<_>>()),
            title: format!("Remediate {what}: {canonical} ({sev})"),
            objective: format!(
                "Health check {canonical}{} fails ({sev}): {}. Find the cause and repair it through its governed route (a CIT for governed state, a task for product or test changes); the remediation is verified by the check passing when it is re-evaluated (`gov health run`, `gov audit`, `gov doctor`), not by this task's report.",
                if members.len() > 1 || members.first() != Some(&canonical) { format!(" (reported by {})", members.join(", ")) } else { String::new() },
                if msgs.is_empty() { "see the health state (`gov health status`)".to_string() } else { msgs.join("; ") }
            ),
            paths,
            remedies: {
                let mut r = members.clone();
                if !r.contains(&canonical) {
                    r.push(canonical.clone());
                }
                r
            },
            detail: json!({"check": canonical, "members": members, "severity": sev, "findings": findings.iter().take(20).cloned().collect::<Vec<_>>(), "governance_suite_record": record, "health_state_at": at}),
            ..Default::default()
        });
    }
    out
}

/// **Research discoveries** (Contract v3:576): what a worker's return (`handoff return`) or a sealed close report
/// says it discovered, left unresolved or proposes to decide. One follow-up per item; an item reported both in the
/// return and in the close report of the same task is one piece of work.
pub fn discoveries(g: &GenCtx) -> Vec<Candidate> {
    let mut out = vec![];
    let mut push = |task: &str, record: &str, at: &str, v: &Value| {
        for (field, source, what) in [
            ("discoveries", "research-discovery", "discovery"),
            ("unresolved", "research-discovery", "unresolved item"),
            (
                "proposed_decisions",
                "proposed-decision",
                "proposed decision",
            ),
        ] {
            for item in v[field].as_array().cloned().unwrap_or_default() {
                let text = text_of(&item);
                if g.cfg.trivial(&text) {
                    continue;
                }
                let h = digest(&[field.to_string(), text.trim().to_lowercase()]);
                let scope = if task.is_empty() { record } else { task };
                let subject = format!("{scope}#{field}#{h}");
                let objective = match field {
                    "proposed_decisions" => format!("Prepare the decision proposed by {record}{}: '{}'. Assemble the decision package (options, impact, reversibility, recommendation) and raise it as a Human Decision Gate or, within policy, resolve it with its rationale; link the result to this task.", if task.is_empty() { String::new() } else { format!(" (task {task})") }, clip(&text, 400)),
                    _ => format!("Follow up the {what} reported by {record}{}: '{}'. Decide what governed work it calls for — a requirement or scenario, a CIT, a decision gate, research or a task — create and link it (derived from this task), or record why none is needed.", if task.is_empty() { String::new() } else { format!(" (task {task})") }, clip(&text, 400)),
                };
                out.push(Candidate {
                    source: source.into(),
                    subject: subject.clone(),
                    occurrence: h.clone(),
                    evidence_at: at.to_string(),
                    records: vec![record.to_string()],
                    title: format!("Follow up {what} from {scope}: {}", clip(&text, 80)),
                    objective,
                    detail: json!({"field": field, "item": item, "reported_by": record, "task": task}),
                    ..Default::default()
                });
            }
        }
    };
    for h in g.store.of_type("handoff") {
        let ret = &h.data["return"];
        if !ret.is_object() {
            continue;
        }
        let at = h.get("returned_at");
        push(&h.get("task"), &h.id(), &at, ret);
    }
    for r in g.store.of_type("report") {
        // only the OS-written close report counts (a hand-written report states nothing the OS recorded)
        if !crate::t2::verify_record(r).is_verified() {
            continue;
        }
        let at = r.data["mutation_evidence"]["closed_at"]
            .as_str()
            .map(|s| s.to_string())
            .unwrap_or_else(|| r.get("created"));
        push(&r.get("task"), &r.id(), &at, &r.data);
    }
    for c in out.iter_mut() {
        c.records = g.linkable(&c.records);
    }
    out
}

/// **Human decisions** (Contract v3:577): a T2-verified decision derived from a human's answer to a gate an agent
/// raised. A gate the OS raised for one of its own operations (a CIT, a budget, a profile, a promotion, an update) is
/// applied by that operation, and an authorising answer to a gate that governs tasks releases those tasks — they carry
/// the decision. Otherwise the decision is carried out by generated work; a declining answer that stops governed work
/// generates the work of replanning it.
pub fn human_decisions(g: &GenCtx) -> Vec<Candidate> {
    let mut out = vec![];
    for d in g.store.of_type("decision") {
        let human = d
            .data
            .get("human_approved")
            .and_then(|v| v.as_bool())
            .unwrap_or(false)
            || d.get("approved_by_kind") == "human";
        if !human || !crate::t2::verify_record(d).is_verified() {
            continue;
        }
        if matches!(
            d.status().as_str(),
            "SUPERSEDED" | "REJECTED" | "HISTORICAL" | "RETIRED"
        ) {
            continue;
        }
        let Some(gate_id) = d
            .list("derived_from")
            .into_iter()
            .find(|x| x.starts_with("HDG-"))
        else {
            continue;
        };
        let Some(gate) = g.store.get(&gate_id) else {
            continue;
        };
        if gate.data["raised_by"]["kind"].as_str() == Some("system")
            || !gate.get("cit").is_empty()
            || !d.get("cit").is_empty()
        {
            continue; // the OS operation that raised the gate applies its answer
        }
        let mut governed: Vec<String> = gate.list("blocks_tasks");
        for t in g.store.of_type("task") {
            if t.get("human_gate") == gate_id && !governed.contains(&t.id()) {
                governed.push(t.id());
            }
        }
        let declined = d
            .data
            .get("declined")
            .and_then(|v| v.as_bool())
            .unwrap_or(false);
        if !declined && !governed.is_empty() {
            continue; // the released work carries the decision
        }
        let option = d.get("chosen_option");
        let option_text = gate.data["options"]
            .as_array()
            .and_then(|a| a.iter().find(|o| o["id"].as_str() == Some(option.as_str())))
            .map(|o| text_of(o))
            .unwrap_or_default();
        let question = gate.get("question");
        let (title, objective, affects) = if declined && !governed.is_empty() {
            (
                format!("Replan the work stopped by decision {} ({gate_id})", d.id()),
                format!("The human answered {gate_id} ('{}') with option {option}{}, which does not authorise the work it governs ({}). Replan it: cancel it, rework or re-scope it within the decision, or raise a new gate with a changed proposal.", clip(&question, 200), if option_text.is_empty() { String::new() } else { format!(" ({})", clip(&option_text, 120)) }, governed.join(", ")),
                governed.clone(),
            )
        } else {
            (
                format!("Carry out human decision {} ({gate_id}, option {option})", d.id()),
                format!("The human decided {gate_id} ('{}'): option {option}{}. Carry the decision out in the governed plan — update or create the requirements, decisions, CITs and tasks it requires (derived from {}) — or record why it requires no further work.", clip(&question, 200), if option_text.is_empty() { String::new() } else { format!(" — {}", clip(&option_text, 200)) }, d.id()),
                vec![],
            )
        };
        out.push(Candidate {
            source: "human-decision".into(),
            subject: d.id(),
            occurrence: d.id(),
            evidence_at: d
                .data
                .get("approved_at")
                .and_then(|v| v.as_str())
                .map(|s| s.to_string())
                .unwrap_or_else(|| d.get("created")),
            records: g.linkable(&[d.id()]),
            title,
            objective,
            affects,
            detail: json!({"decision": d.id(), "gate": gate_id, "option": option, "declined": declined, "governed_tasks": governed}),
            ..Default::default()
        });
    }
    out
}

/// **CIT effects** (Contract v3:578, :1134 "revalidation/rework tasks are generated"): completed work an upstream
/// change marked `revalidation.required` for which no revalidation task exists — propagation generates it when the
/// acting role may create tasks and marks it pending otherwise; this completes it. Open dependents are their own
/// rework (marked `retest_required`; they close only with re-test evidence).
pub fn cit_effects(g: &GenCtx) -> Vec<Candidate> {
    let revalidating: BTreeSet<String> = g
        .store
        .of_type("task")
        .into_iter()
        .map(|t| t.get("revalidates"))
        .filter(|x| !x.is_empty())
        .collect();
    let mut out = vec![];
    for t in g.store.of_type("task") {
        if t.get("task_status") != "DONE"
            || t.data["revalidation"]["required"].as_bool() != Some(true)
            || revalidating.contains(&t.id())
        {
            continue;
        }
        let tid = t.id();
        let changed: Vec<String> = t.data["staleness"]["inputs_changed"]
            .as_array()
            .map(|a| {
                a.iter()
                    .filter_map(|x| x["id"].as_str().map(|s| s.to_string()))
                    .collect()
            })
            .unwrap_or_default();
        let mut fields = json!({"revalidates": tid, "revalidation_of": {"task": tid, "report": t.get("closed_by_report"), "cause": t.data["revalidation"]["cause"], "inputs_changed": t.data["staleness"]["inputs_changed"]}});
        for k in [
            "feature",
            "requirements",
            "decisions",
            "scenarios",
            "acceptance_tests",
            "interfaces",
            "architecture",
            "required_data",
            "required_inputs",
            "optional_inputs",
            "allowed_paths",
            "forbidden_paths",
        ] {
            if let Some(v) = t.data.get(k).filter(|v| !v.is_null()) {
                fields[k] = v.clone();
            }
        }
        let paths = t.list("allowed_paths");
        out.push(Candidate {
            source: "cit-effect".into(),
            subject: tid.clone(),
            occurrence: tid.clone(),
            evidence_at: t.data["revalidation"]["at"]
                .as_str()
                .unwrap_or("")
                .to_string(),
            records: g.linkable(&[t.get("closed_by_report")]),
            title: format!("Revalidate {tid} after its inputs changed"),
            objective: format!("Revalidate the completed work of {tid} ({}) against its changed inputs {}: re-run its acceptance evidence at the current input versions, rework what no longer holds, and close with a consumption receipt at the current hashes (its close resolves {tid}'s revalidation).", t.title(), changed.join(", ")),
            paths,
            fields,
            detail: json!({"revalidates": tid, "inputs_changed": changed, "cause": t.data["revalidation"]["cause"]}),
            ..Default::default()
        });
    }
    out
}

