/// The kernel taxonomy `taxonomy/WORK_GENERATION.yaml` (the installed kernel's copy; the embedded one when the
/// installation predates it).
#[derive(Debug, Clone)]
pub struct Config {
    raw: Value,
}

impl Config {
    pub fn load(p: &Project) -> Config {
        let installed = p.kernel_dir().join("taxonomy").join("WORK_GENERATION.yaml");
        let raw = crate::util::read_yaml(&installed)
            .ok()
            .filter(|v| v.get("sources").is_some())
            .unwrap_or_else(Self::embedded_raw);
        Config { raw }
    }
    fn embedded_raw() -> Value {
        serde_yaml::from_str(DEFAULT_TAXONOMY).unwrap_or(json!({}))
    }
    /// The embedded taxonomy (tests; installations that predate it).
    pub fn embedded() -> Config {
        Config {
            raw: Self::embedded_raw(),
        }
    }
    fn list(&self, key: &str) -> Vec<String> {
        self.raw[key]
            .as_array()
            .map(|a| {
                a.iter()
                    .filter_map(|x| x.as_str().map(|s| s.to_string()))
                    .collect()
            })
            .unwrap_or_default()
    }
    /// `(class, designated role, allowed paths, contract line)` of a source.
    pub fn source(&self, kind: &str) -> (String, Option<String>, Vec<String>, String) {
        let s = &self.raw["sources"][kind];
        (
            s["class"].as_str().unwrap_or("governance").to_string(),
            s["role"]
                .as_str()
                .filter(|r| !r.is_empty())
                .map(|r| r.to_string()),
            s["paths"]
                .as_array()
                .map(|a| {
                    a.iter()
                        .filter_map(|x| x.as_str().map(|s| s.to_string()))
                        .collect()
                })
                .unwrap_or_default(),
            s["contract"]
                .as_str()
                .unwrap_or("Contract v3:571-583")
                .to_string(),
        )
    }
    pub fn severity_threshold(&self) -> String {
        self.raw["severity_threshold"]
            .as_str()
            .unwrap_or("medium")
            .to_string()
    }
    fn canonical_check(&self, id: &str) -> String {
        self.raw["same_condition"][id]
            .as_str()
            .unwrap_or(id)
            .to_string()
    }
    fn trivial(&self, item: &str) -> bool {
        let t = item.trim().trim_end_matches('.').to_lowercase();
        t.len() < 2 || self.list("trivial_items").iter().any(|x| *x == t)
    }
    fn perf(&self, key: &str) -> Value {
        self.raw["performance"][key].clone()
    }
}

