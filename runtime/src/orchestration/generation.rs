/// **Missing tools and skills** (Contract v3:580): open work requiring a tool or skill that does not resolve. One
/// task per missing capability, which `blocks` every task that needs it (more work needing it later is added).
pub fn missing_capabilities(g: &GenCtx) -> Vec<Candidate> {
    let r = crate::orchestration::dag::InputResolver::new(g.p, g.store);
    // (kind, id) -> (needing tasks, earliest created)
    let mut need: BTreeMap<(&'static str, String), (Vec<String>, String)> = BTreeMap::new();
    for t in g.store.of_type("task") {
        if matches!(t.get("task_status").as_str(), "DONE" | "CANCELLED") || source_of(t).is_some() {
            continue;
        }
        for (kind, field) in [
            ("missing-tool", "required_tools"),
            ("missing-skill", "required_skills"),
        ] {
            for id in t.list(field) {
                let missing = if kind == "missing-tool" {
                    r.tool(&id).is_err()
                } else {
                    r.skill(&id).is_err()
                };
                if missing {
                    let e = need
                        .entry((kind, id.clone()))
                        .or_insert((vec![], t.get("created")));
                    e.0.push(t.id());
                    let c = t.get("created");
                    if !c.is_empty() && (e.1.is_empty() || c < e.1) {
                        e.1 = c;
                    }
                }
            }
        }
    }
    let mut out = vec![];
    for ((kind, id), (tasks, at)) in need {
        let what = if kind == "missing-tool" {
            "tool"
        } else {
            "skill"
        };
        let how = if kind == "missing-tool" {
            "register an existing tool (`gov tools install <descriptor>`, the capability registry) or build it as governed tooling"
        } else {
            "add the skill to the project's governed skills (its method and validation scenarios), or change the tasks to use an existing skill"
        };
        out.push(Candidate {
            source: kind.into(),
            subject: id.clone(),
            occurrence: id.clone(),
            evidence_at: if at.is_empty() { now_iso() } else { at },
            records: vec![],
            title: format!("Provide the missing {what} '{id}'"),
            objective: format!("Tasks {} require the {what} '{id}', which does not resolve. Provide it: {how}. The tasks it blocks become runnable once it resolves.", tasks.join(", ")),
            blocks: tasks.clone(),
            detail: json!({"capability": what, "id": id, "needed_by": tasks}),
            ..Default::default()
        });
    }
    out
}

/// **Retrieval failures and other failure memory** (Contract v3:581; framework §11.8, §18): every failure record
/// whose follow-up is still open. The task is linked back from the record (`follow_up.task`).
pub fn failures(g: &GenCtx) -> Vec<Candidate> {
    let open: BTreeSet<String> = crate::memory::failures::open_failures(g.p)
        .into_iter()
        .filter_map(|f| f["id"].as_str().map(|s| s.to_string()))
        .collect();
    let mut out = vec![];
    for (path, v) in crate::memory::failures::list(g.p) {
        let id = v["id"].as_str().unwrap_or("").to_string();
        if !open.contains(&id) {
            continue;
        }
        let kind = v["failure_kind"].as_str().unwrap_or("bug").to_string();
        let source = match kind.as_str() {
            "retrieval-miss" => "retrieval-failure",
            "tool-failure" => "tool-failure",
            "regression" if v["subject"]["performance"].as_bool() == Some(true) => {
                "performance-regression"
            }
            _ => "failure",
        };
        let actions: Vec<String> = v["follow_up"]["required_actions"]
            .as_array()
            .map(|a| a.iter().map(text_of).collect())
            .unwrap_or_default();
        out.push(Candidate {
            source: source.into(),
            subject: id.clone(),
            occurrence: v["signature"].as_str().unwrap_or(&id).to_string(),
            evidence_at: v["occurred_at"].as_str().unwrap_or("").to_string(),
            records: g.linkable(&[id.clone()]),
            title: format!("Follow up {kind} {id}: {}", clip(v["title"].as_str().unwrap_or(""), 80)),
            objective: format!("Failure {id} ({kind}, {path}): {}. Establish the root cause and repair it{}; framework §18: a retrieval failure is fixed at its cause and gains a held-out query that would have caught it.", clip(v["summary"].as_str().unwrap_or(""), 400), if actions.is_empty() { String::new() } else { format!(" — required: {}", actions.join("; ")) }),
            failure: Some(id.clone()),
            detail: json!({"failure": id, "failure_kind": kind, "path": path, "subject": v["subject"], "root_cause_candidates": v["root_cause_candidates"]}),
            ..Default::default()
        });
    }
    out
}

/// **Performance regressions** (Contract v3:583): a product measurement reported to the OS (`gov telemetry emit`) that
/// exceeds its declared baseline — or, for a performance-namespaced metric, the median of its earlier samples — by the
/// policy factor and margin. Each regression becomes a durable `regression` failure record (the telemetry log is
/// derived state), which [`failures`] turns into linked `performance` work. Telemetry of the Governance OS itself is
/// excluded (its SLOs are Gate U).
pub fn detect_performance_regressions(g: &GenCtx, record: bool) -> Vec<Value> {
    let cfg = &g.cfg;
    let factor = cfg.perf("factor").as_f64().unwrap_or(1.5);
    let min_delta = cfg.perf("min_delta_ms").as_f64().unwrap_or(10.0);
    let min_samples = cfg.perf("min_samples").as_u64().unwrap_or(5) as usize;
    let strs = |k: &str| -> Vec<String> {
        cfg.perf(k)
            .as_array()
            .map(|a| {
                a.iter()
                    .filter_map(|x| x.as_str().map(|s| s.to_string()))
                    .collect()
            })
            .unwrap_or_default()
    };
    let (measures, baselines, own, history_ns) = (
        strs("measures"),
        strs("baselines"),
        strs("own_namespaces"),
        strs("history_namespaces"),
    );
    let mut history: BTreeMap<(String, String), Vec<f64>> = BTreeMap::new();
    let mut found = vec![];
    for ev in crate::observability::events(g.p) {
        let name = ev["name"].as_str().unwrap_or("").to_string();
        if name.is_empty() || own.iter().any(|o| name.starts_with(o.as_str())) {
            continue;
        }
        let a = &ev["attributes"];
        let Some((measure, value)) = measures
            .iter()
            .find_map(|m| a[m.as_str()].as_f64().map(|v| (m.clone(), v)))
        else {
            continue;
        };
        let declared = baselines.iter().find_map(|b| a[b.as_str()].as_f64());
        let hist = history.entry((name.clone(), measure.clone())).or_default();
        let baseline = match declared {
            Some(b) => Some((b, "declared baseline")),
            None if history_ns.iter().any(|h| name.starts_with(h.as_str()))
                && hist.len() >= min_samples =>
            {
                let mut v = hist.clone();
                v.sort_by(|x, y| x.partial_cmp(y).unwrap_or(std::cmp::Ordering::Equal));
                Some((v[v.len() / 2], "median of earlier samples"))
            }
            None => None,
        };
        hist.push(value);
        let Some((base, basis)) = baseline else {
            continue;
        };
        if value > base * factor && value - base >= min_delta {
            found.push(json!({"metric": name, "measure": measure, "value": value, "baseline": base, "basis": basis,
                "factor": factor, "at": ev["timestamp"], "session": ev["session"], "attributes": a}));
        }
    }
    // one durable failure record per regression signature (metric, measure, baseline)
    if record {
        for r in &found {
            let ev = crate::memory::failures::FailureEvent {
                kind: "regression".into(),
                signature_basis: json!({"metric": r["metric"], "measure": r["measure"], "baseline": r["baseline"]}),
                title: format!("Performance regression: {} {} {} vs baseline {}", r["metric"].as_str().unwrap_or("?"), r["measure"].as_str().unwrap_or("?"), r["value"], r["baseline"]),
                summary: format!("{} measured {} = {} against a {} of {} (policy: more than {}x and at least {} ms worse)", r["metric"].as_str().unwrap_or("?"), r["measure"].as_str().unwrap_or("?"), r["value"], r["basis"].as_str().unwrap_or(""), r["baseline"], factor, min_delta),
                subject: json!({"performance": true, "metric": r["metric"], "measure": r["measure"], "value": r["value"], "baseline": r["baseline"], "basis": r["basis"], "observed_at": r["at"]}),
                root_cause_candidates: vec!["a change since the baseline was measured".into(), "environment or load".into()],
                required_actions: vec!["reproduce the measurement".into(), "find the change that caused it".into(), "repair it or record an accepted new baseline through a decision".into()],
                operation: "work generation (telemetry)".into(),
                detection: "automatic".into(),
            };
            // `true`: a current index is kept current for the new record (a stale one is left as it was)
            let _ = crate::memory::failures::record(g.p, ev, true);
        }
    }
    found
}

/// Every candidate of every source, in source order, with each source's errors isolated.
pub fn candidates(g: &GenCtx) -> Vec<Candidate> {
    let mut v = vec![];
    v.extend(failed_tests(g));
    v.extend(health_failures(g));
    v.extend(discoveries(g));
    v.extend(human_decisions(g));
    v.extend(cit_effects(g));
    v.extend(lessons(g));
    v.extend(missing_capabilities(g));
    v.extend(failures(g));
    v
}

