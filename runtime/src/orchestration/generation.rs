/// One piece of work an event calls for.
#[derive(Debug, Clone, Default)]
pub struct Candidate {
    /// Source kind (a key of the taxonomy's `sources`).
    pub source: String,
    /// What the work is about, stable across occurrences (a check, a family, a record, a tool, …).
    pub subject: String,
    /// What occurred (a record id, or a digest of what failed): with source and subject it keys the work.
    pub occurrence: String,
    /// When the evidence of the occurrence was produced (RFC 3339 or a date).
    pub evidence_at: String,
    /// Governed source records the work is derived from.
    pub records: Vec<String>,
    pub title: String,
    pub objective: String,
    /// Allowed paths (empty = the taxonomy's for the source).
    pub paths: Vec<String>,
    /// Tasks the work unblocks (its `blocks`).
    pub blocks: Vec<String>,
    /// Records the work acts on (`AFFECTS` relations).
    pub affects: Vec<String>,
    /// Health checks the work remedies.
    pub remedies: Vec<String>,
    /// Failure-memory record to link to the task (`memory::failures::link_follow_up`).
    pub failure: Option<String>,
    /// Extra task fields (e.g. the inputs of the work a revalidation task revalidates).
    pub fields: Value,
    pub detail: Value,
}

impl Candidate {
    /// The occurrence key: `GEN-` + 16 hex of source, subject and occurrence.
    pub fn key(&self) -> String {
        key_of(&self.source, &self.subject, &self.occurrence)
    }
    pub fn to_value(&self) -> Value {
        json!({"source": self.source, "subject": self.subject, "occurrence": self.occurrence, "key": self.key(),
               "evidence_at": self.evidence_at, "records": self.records, "title": self.title, "blocks": self.blocks,
               "affects": self.affects, "remedies": self.remedies, "failure": self.failure})
    }
}

pub fn key_of(source: &str, subject: &str, occurrence: &str) -> String {
    format!(
        "GEN-{}",
        &sha256_hex(format!("{source}\u{1f}{subject}\u{1f}{occurrence}").as_bytes())[..16]
    )
}

fn digest(parts: &[String]) -> String {
    sha256_hex(parts.join("\u{1f}").as_bytes())[..16].to_string()
}

/// Epoch seconds of an RFC 3339 timestamp or a `YYYY-MM-DD` date.
fn epoch(s: &str) -> Option<i64> {
    if let Ok(d) = chrono::DateTime::parse_from_rfc3339(s) {
        return Some(d.timestamp());
    }
    chrono::NaiveDate::parse_from_str(s.get(..10).unwrap_or(s), "%Y-%m-%d")
        .ok()
        .and_then(|d| d.and_hms_opt(0, 0, 0))
        .map(|d| d.and_utc().timestamp())
}

fn text_of(v: &Value) -> String {
    match v {
        Value::String(s) => s.clone(),
        Value::Object(o) => ["text", "description", "summary", "title", "question", "id"]
            .iter()
            .find_map(|k| o.get(*k).and_then(|x| x.as_str()).map(|s| s.to_string()))
            .unwrap_or_else(|| v.to_string()),
        Value::Null => String::new(),
        other => other.to_string(),
    }
}

fn clip(s: &str, n: usize) -> String {
    let t: String = s.chars().take(n).collect();
    if t.len() < s.len() {
        format!("{t}…")
    } else {
        t
    }
}

