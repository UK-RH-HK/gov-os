//! **Governed work generated from events** (BC-P2-24; Contract v3:571-583 I3 "Tasks can be generated from: readiness
//! gaps, failed tests, audit findings, research discoveries, human decisions, CIT effects, lessons, missing
//! tools/skills, retrieval failures, security findings, performance regressions"; framework §43 "The WBS is therefore
//! a continuously compiled execution graph, not a static plan"; frozen gate contract AC-5 "remediation/task
//! generation", from each health failure).
//!
//! ## One engine, every source
//!
//! Each source is a **detector over what the event durably left** — a recorded product-test run, the health state and
//! the governance-suite record, a worker's return and a sealed close report, a decision derived from a human answer,
//! a completed task a CIT marked for revalidation, a lesson record, a task requiring a tool or skill that does not
//! resolve, a failure-memory record, a telemetry measurement — never a label the caller asserts. For every occurrence
//! it proposes one piece of work ([`Candidate`]); [`reconcile`] turns the proposals into governed, linked tasks in the
//! same DAG as all other work:
//!
//! | source | detected from | the work |
//! |---|---|---|
//! | failed tests (:574) | the latest honoured product-test records (`verification::product`): a family failing in its latest run | `repair` the family (derived from the failing run) |
//! | audit findings (:575), each health failure (AC-5, O5) | the health scheduler state (families and doctor checks failing at or above the policy severity) with the findings of the latest honoured governance-suite record | remediate the check (`remedies: [check]`) |
//! | security findings (:582) | the same, for security checks (secrets, T2 bindings, kernel/installation integrity, plugins) | `security` remediation of the named paths |
//! | research discoveries (:576) | worker returns (`handoff return`) and sealed close reports: `discoveries`, `unresolved`, `proposed_decisions` | follow up each item (`discovery` / `decision-preparation`) |
//! | human decisions (:577) | T2-verified decisions derived from a human answer to a gate an agent raised | carry the decision out; replan the work a declining answer stops |
//! | CIT effects (:578) | completed work a CIT marked `revalidation.required` with no revalidation task (propagation generates it when it may; this completes it when it could not) | `validation` that `revalidates` the work |
//! | lessons (:579) | lesson records (candidate or active) | act on the lesson or route it upstream |
//! | missing tools/skills (:580) | open tasks whose `required_tools` / `required_skills` do not resolve (`dag::InputResolver`) | provide it; the task `blocks` every task that needs it |
//! | retrieval failures (:581) and other failure memory | open failure-memory records (`memory::failures::open_failures`) | root-cause and repair; the record's `follow_up` is linked to the task (`link_follow_up`) |
//! | performance regressions (:583) | telemetry measurements against their declared baseline or their own history | a durable `regression` failure record, then `performance` work linked to it |
//!
//! Readiness gaps (:573) are generated by the readiness planner (`readiness::plan`); W7 orphans by the lineage family's
//! remediation (`verification::lineage`, WS-2); revalidation of completed work by upstream-change propagation
//! (`cit::propagation`, WS-4). The engine **adopts** that work ([`source_of`]): it counts as the generated work of
//! its source, so the engine never duplicates it, and it is listed with everything else (`gov task generate`).
//!
//! ## Linked, idempotent, governed
//!
//! * **Linked.** A generated task is `derived_from` its source record(s) (a DERIVED_FROM edge in the graph, and the
//!   source is delivered to the worker as evidence), carries `generation: {source, subject, key, occurrence,
//!   records, detected_by, detected_at, contract, detail}`, `blocks` the tasks it unblocks and `AFFECTS` the tasks it
//!   replans. A failure record's `follow_up.task` names it.
//! * **Idempotent.** An occurrence has a stable key (source, subject and what occurred); at most one task exists per
//!   key, and at most one open task per source subject. A cancelled task means "not for this occurrence"; after a
//!   completed task, the same subject generates again only on evidence newer than that completion.
//! * **Governed.** Tasks are created through `tasks::create_generated`: the write guard applies (nothing is generated
//!   under FREEZE_WRITES / PAUSE, below floor or on an unverified kernel), the status is the one the DAG derives, the
//!   provenance is the generator's, and the designated role and class come from the kernel taxonomy
//!   (`taxonomy/WORK_GENERATION.yaml`). Remediation of a health failure names the check it `remedies`, so it stays
//!   available under the hard-block it remedies (availability rule) and still commits only by clearing it.
//! * **When the event occurs.** [`reconcile`] runs after every governed write command (`after_command`, the CLI's
//!   one post-command site), inside `task close`, `continue` and `task replan`, and on demand (`gov task generate`).
//!   Read-only commands never write: an event a read-only command observes and records durably (a retrieval miss, a
//!   doctor result in the health state) is turned into work by the next governed operation.
//! * **No loops.** Findings about generated work itself never generate work.
