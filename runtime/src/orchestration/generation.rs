/// A task that is the generated work of some source (generated here, or adopted).
#[derive(Debug, Clone)]
pub struct Generated {
    pub task: String,
    pub status: String,
    pub source: String,
    pub subject: String,
    pub key: String,
    /// The occurrence key without its recurrence suffix.
    pub base_key: String,
    pub closed_at: String,
    pub blocks: Vec<String>,
    pub adopted: bool,
}

impl Generated {
    fn open(&self) -> bool {
        !matches!(self.status.as_str(), "DONE" | "CANCELLED")
    }
}

/// **Which event a task was generated from**, for generated and adopted work: the generation block this engine writes;
/// W7 orphan investigations (`generated_by: health:lineage_orphans`, `investigates`); revalidation tasks
/// (`revalidates`, generated by upstream-change propagation); readiness gap tasks (`generated_by:
/// readiness-planner`). `None` for work an operator created.
pub fn source_of(t: &Record) -> Option<Value> {
    if let Some(g) = t.data.get("generation").filter(|g| g.is_object()) {
        return Some(
            json!({"source": g["source"], "subject": g["subject"], "key": g["key"], "records": g["records"], "detected_by": g["detected_by"], "generator": GENERATOR}),
        );
    }
    if t.get("generated_by") == W7_GENERATOR {
        return Some(
            json!({"source": "orphan", "subject": t.data["investigates"]["subject"], "key": t.data["investigates"]["key"], "adopted": true, "generator": W7_GENERATOR, "contract": "Contract v3:1138-1144 W7"}),
        );
    }
    let rv = t.get("revalidates");
    if !rv.is_empty() {
        return Some(
            json!({"source": "cit-effect", "subject": rv, "key": key_of("cit-effect", &rv, &rv), "adopted": !t.data.get("generation").is_some(), "generator": t.get("generated_by"), "contract": "Contract v3:578; :1134"}),
        );
    }
    if t.get("generated_by") == "readiness-planner" {
        let subject = format!("{}#{}", t.get("feature"), t.get("readiness_cell"));
        return Some(
            json!({"source": "readiness-gap", "subject": subject, "key": key_of("readiness-gap", &subject, &subject), "adopted": true, "generator": "readiness-planner", "contract": "Contract v3:573"}),
        );
    }
    None
}

/// Every generated or adopted task.
pub fn existing(store: &RecordStore) -> Vec<Generated> {
    let mut out = vec![];
    for t in store.of_type("task") {
        let Some(s) = source_of(t) else { continue };
        let key = s["key"].as_str().unwrap_or("").to_string();
        let base_key = t.data["generation"]["base_key"]
            .as_str()
            .map(|x| x.to_string())
            .unwrap_or_else(|| key.clone());
        out.push(Generated {
            task: t.id(),
            status: t.get("task_status"),
            source: s["source"].as_str().unwrap_or("").to_string(),
            subject: match &s["subject"] {
                Value::String(x) => x.clone(),
                Value::Null => String::new(),
                other => other.to_string(),
            },
            key,
            base_key,
            closed_at: t.get("closed_at"),
            blocks: t.list("blocks"),
            adopted: s["adopted"].as_bool().unwrap_or(false),
        });
    }
    out
}

/// What [`reconcile`] does with a candidate.
#[derive(Debug, Clone, PartialEq)]
pub enum Decision {
    /// Generate a task under this key (a recurrence carries a suffix).
    Create { key: String, recurrence: usize },
    /// Add the candidate's `blocks` to this open task (missing tools/skills needed by more work).
    Augment {
        task: String,
        add_blocks: Vec<String>,
    },
    /// Nothing to do, with why.
    Skip {
        reason: String,
        task: Option<String>,
    },
}

/// **The idempotency rule.** At most one task per occurrence key and at most one open task per source subject; a
/// cancelled task declines its occurrence; after a completed task, the subject generates again only on evidence
/// newer than that completion (the remedy did not hold).
pub fn decide(c: &Candidate, ex: &[Generated]) -> Decision {
    let base = c.key();
    let same_subject: Vec<&Generated> = ex
        .iter()
        .filter(|g| g.source == c.source && g.subject == c.subject)
        .collect();
    if let Some(g) = same_subject.iter().find(|g| g.open()) {
        let add: Vec<String> = c
            .blocks
            .iter()
            .filter(|b| !g.blocks.contains(b) && **b != g.task)
            .cloned()
            .collect();
        if !add.is_empty() && !g.adopted {
            return Decision::Augment {
                task: g.task.clone(),
                add_blocks: add,
            };
        }
        return Decision::Skip {
            reason: "open work for this subject exists".into(),
            task: Some(g.task.clone()),
        };
    }
    let same_occurrence: Vec<&&Generated> = same_subject
        .iter()
        .filter(|g| g.base_key == base || g.key == base)
        .collect();
    if let Some(g) = same_occurrence.iter().find(|g| g.status == "CANCELLED") {
        return Decision::Skip {
            reason: "work for this occurrence was cancelled".into(),
            task: Some(g.task.clone()),
        };
    }
    let evidence = epoch(&c.evidence_at);
    let latest_done = same_subject
        .iter()
        .filter(|g| g.status == "DONE")
        .max_by_key(|g| epoch(&g.closed_at).unwrap_or(0));
    if let Some(d) = latest_done {
        let done_at = epoch(&d.closed_at).unwrap_or(i64::MAX);
        if evidence.map(|e| e <= done_at).unwrap_or(true) {
            return Decision::Skip {
                reason: "the evidence predates the completed work for this subject".into(),
                task: Some(d.task.clone()),
            };
        }
        let n = same_occurrence
            .iter()
            .filter(|g| g.status == "DONE")
            .count();
        if n > 0 {
            return Decision::Create {
                key: format!("{base}-r{n}"),
                recurrence: n,
            };
        }
    }
    if let Some(g) = ex.iter().find(|g| g.key == base) {
        return Decision::Skip {
            reason: "already generated".into(),
            task: Some(g.task.clone()),
        };
    }
    Decision::Create {
        key: base,
        recurrence: 0,
    }
}

