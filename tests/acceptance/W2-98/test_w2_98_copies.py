"""W2-98: the generated copies match the template's source: success-6, failure-5 (DEC-616, DEC-645).

The comparison rule, as the adapter check (``gov.adapters.portability``) applies it:

* ``.rulesync/skills/spec-writing/`` and ``template/.rulesync/skills/spec-writing/`` hold the same files as the
  kernel source; ``SKILL.md`` has the same parsed front matter and the same body; every other file is byte-equal.
* ``.claude/skills/spec-writing/`` (what rulesync generates) holds the same files; ``SKILL.md`` has the same body,
  the same name and description (whitespace collapsed), only keys rulesync writes, and the version under
  ``metadata.version`` (rulesync writes no top-level ``version``); every other file is byte-equal.

KNOWN RED UNTIL THE COPIES ACT (DEC-1112 (3)): the ``.claude/skills/`` cases. A launched session cannot write that
folder (DEC-315); the CTO's copies ACT generates it. They are not skipped and not xfail.

The planted hand edits run in a minimal tree in ``tmp_path`` (a few named files, never the repository).
"""
from __future__ import annotations

import functools
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

import w2_98_support as s

CLAUDE_KEYS = {"name", "description", "when_to_use", "allowed-tools", "disallowed-tools", "model", "effort",
               "argument-hint", "context", "agent", "shell", "background", "arguments", "hooks",
               "disable-model-invocation", "user-invocable", "paths", "license", "compatibility", "metadata"}


def _collapse(text):
    return " ".join(str(text).split())


def differences(source, copy, generated):
    """What differs between a copy folder and the source folder, as a list of messages (empty: no difference)."""
    source, copy = Path(source), Path(copy)
    if not copy.is_dir():
        return [f"{copy} does not exist"]
    found = []
    src, cpy = s.skill_files(source), s.skill_files(copy)
    found += [f"{copy}/{f} is missing" for f in src if f not in cpy]
    found += [f"{copy}/{f} has no source" for f in cpy if f not in src]
    for rel in (f for f in src if f in cpy):
        a, b = source / rel, copy / rel
        if rel.name != "SKILL.md" or len(rel.parts) != 1:
            if a.read_bytes() != b.read_bytes():
                found.append(f"{copy}/{rel} differs from {a}")
            continue
        (fa, ba), (fb, bb) = (s.split_frontmatter(p.read_text(encoding="utf-8")) for p in (a, b))
        if ba != bb:
            found.append(f"{copy}/SKILL.md: the body differs from {a}")
        if fa is None or fb is None:
            found.append(f"{copy}/SKILL.md or its source has no front matter")
        elif not generated:
            if fa != fb:
                found.append(f"{copy}/SKILL.md: the front matter differs from {a}")
        else:
            extra = set(fb) - CLAUDE_KEYS
            version = str(fa.get("version") or (fa.get("metadata") or {}).get("version"))
            if extra:
                found.append(f"{copy}/SKILL.md: keys rulesync does not write: {sorted(extra)}")
            if fb.get("name") != fa.get("name") or _collapse(fb.get("description")) != _collapse(fa.get("description")):
                found.append(f"{copy}/SKILL.md: name or description differs from {a}")
            if str((fb.get("metadata") or {}).get("version")) != version:
                found.append(f"{copy}/SKILL.md: metadata.version is not {version}")
    return found


def _source():
    return s.need(s.SKILL_DIR / "SKILL.md").parent


# success-6 and failure-5 on the real tree ---------------------------------------------------------------------------

@pytest.mark.parametrize("root", [".rulesync/skills", "template/.rulesync/skills"])
def test_the_rulesync_copy_matches_the_kernel_source(root):
    source = _source()
    found = differences(source, s.REPO_ROOT / root / s.SKILL_NAME, generated=False)
    assert not found, f"{root}/{s.SKILL_NAME} differs from the kernel source: {found}"


def test_the_claude_copy_matches_the_kernel_source():
    """KNOWN RED until the CTO's copies ACT (DEC-1112 (3)): .claude/skills/ is generated by it, not by this ticket."""
    source = _source()
    found = differences(source, s.REPO_ROOT / ".claude/skills" / s.SKILL_NAME, generated=True)
    assert not found, f".claude/skills/{s.SKILL_NAME} differs from the kernel source: {found}"


def _adapter(cwd):
    env = {**os.environ, "PYTHONPATH": os.pathsep.join([str(s.REPO_ROOT / "src"), os.environ.get("PYTHONPATH", "")])}
    done = subprocess.run([sys.executable, "-m", "gov.adapters.portability"], capture_output=True, text=True,
                          cwd=str(cwd), env=env, timeout=120, stdin=subprocess.DEVNULL)
    return done.returncode, json.loads(done.stdout)["findings"]


def _naming_the_skill(findings):
    return [f for f in findings if s.SKILL_NAME in f.get("file", "") or s.SKILL_NAME in f.get("message", "")]


@functools.lru_cache(maxsize=1)
def _real_findings():
    """The adapter check's findings on the real tree (one run for the module)."""
    return _adapter(s.REPO_ROOT)[1]


def test_the_adapter_check_finds_no_source_drift_in_the_real_skill():
    _source()
    findings = _real_findings()
    source_side = [f for f in _naming_the_skill(findings) if f["code"].startswith("SOURCE_")]
    assert not source_side, f"the adapter check names the skill's rulesync sources: {source_side}"


def test_the_adapter_check_finds_no_generated_drift_in_the_real_skill():
    """KNOWN RED until the CTO's copies ACT (DEC-1112 (3)): the .claude/skills/ copy is generated by it."""
    if shutil.which("rulesync") is None and not os.environ.get("RULESYNC_BIN"):
        pytest.skip("rulesync is not installed: the adapter check cannot compare the generated copy")
    _source()
    findings = _real_findings()
    generated = [f for f in _naming_the_skill(findings) if f["code"].startswith("GENERATED_")]
    assert not generated, f"the adapter check names the skill's generated copy: {generated}"


# the planted hand edits: a minimal tree in tmp_path -----------------------------------------------------------------

def _plant_tree(tmp_path):
    """A minimal repository: the skill's files under the kernel's skills folder and byte copies in .rulesync."""
    source = _source()
    kernel = tmp_path / "template/governance/kernel/skills" / s.SKILL_NAME
    mirror = tmp_path / ".rulesync/skills" / s.SKILL_NAME
    for folder in (kernel, mirror):
        folder.mkdir(parents=True)
        for rel in s.skill_files(source):
            (folder / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source / rel, folder / rel)
    return kernel, mirror


@pytest.mark.parametrize("name", ["spec-form.md", "check_spec.py", "SKILL.md"])
def test_a_hand_edit_in_the_rulesync_copy_is_named_by_the_adapter_check(tmp_path, name):
    kernel, mirror = _plant_tree(tmp_path)
    _, before = _adapter(tmp_path)
    assert not [f for f in before if f["code"] == "SOURCE_DIFFERS"], f"the untouched copy already differs: {before}"
    target = mirror / name
    text = target.read_text(encoding="utf-8")
    target.write_text(text + "\nA line added by hand.\n", encoding="utf-8")
    code, findings = _adapter(tmp_path)
    expected = f".rulesync/skills/{s.SKILL_NAME}/{name}"
    named = [f for f in findings if f["code"] == "SOURCE_DIFFERS" and f.get("file") == expected]
    assert code == 1 and named, f"the adapter check does not name {expected} with SOURCE_DIFFERS: {findings}"


def test_a_hand_edit_in_the_claude_copy_is_named_by_the_adapter_check(tmp_path):
    rulesync = shutil.which("rulesync") or os.environ.get("RULESYNC_BIN")
    if not rulesync:
        pytest.skip("rulesync is not installed: the adapter check cannot generate the .claude/skills copy to compare")
    kernel, mirror = _plant_tree(tmp_path)
    (tmp_path / ".rulesync/rules").mkdir(parents=True)
    (tmp_path / ".rulesync/rules/governance.md").write_text(
        '---\nroot: true\ntargets: ["claudecode", "agentsmd"]\ndescription: "Rules"\n---\n\n# Rules\n\nPlanted.\n',
        encoding="utf-8")
    version = subprocess.run([rulesync, "--version"], capture_output=True, text=True, timeout=30).stdout.strip()
    (tmp_path / "governance/project").mkdir(parents=True)
    (tmp_path / "governance/project/tool-registry.yaml").write_text(
        f'tools:\n  - name: rulesync\n    version: "{version}"\n', encoding="utf-8")
    made = subprocess.run([rulesync, "generate", "--targets", "claudecode,agentsmd", "--features",
                           "rules,hooks,permissions,subagents,commands,skills", "--input-roots",
                           str((tmp_path / ".rulesync").resolve())],
                          capture_output=True, text=True, cwd=str(tmp_path), timeout=60, stdin=subprocess.DEVNULL)
    assert made.returncode == 0, f"rulesync generate failed in the planted tree: {(made.stderr or made.stdout)[-300:]}"
    generated = tmp_path / ".claude/skills" / s.SKILL_NAME
    assert generated.is_dir(), "rulesync wrote no .claude/skills copy of the planted skill"
    _, before = _adapter(tmp_path)
    assert not [f for f in before if f["code"].startswith("GENERATED_")], f"the untouched copy drifts: {before}"
    target = generated / "spec-form.md"
    target.write_text(target.read_text(encoding="utf-8") + "\nA line added by hand.\n", encoding="utf-8")
    code, findings = _adapter(tmp_path)
    expected = f".claude/skills/{s.SKILL_NAME}/spec-form.md"
    named = [f for f in findings if f["code"] == "GENERATED_DIFFERS" and f.get("file") == expected]
    assert code == 1 and named, f"the adapter check does not name {expected} with GENERATED_DIFFERS: {findings}"


def test_the_comparison_finds_a_planted_difference_and_passes_the_untouched_copy(tmp_path):
    """The test's own comparison, shown on planted copies: an edit in each kind of file is found."""
    kernel, mirror = _plant_tree(tmp_path)
    assert differences(kernel, mirror, generated=False) == []
    (mirror / "check_spec.py").write_text((mirror / "check_spec.py").read_text(encoding="utf-8") + "# edit\n",
                                          encoding="utf-8")
    assert any("check_spec.py" in d for d in differences(kernel, mirror, generated=False))
    shutil.copyfile(kernel / "check_spec.py", mirror / "check_spec.py")
    (mirror / "SKILL.md").write_text((mirror / "SKILL.md").read_text(encoding="utf-8") + "\nedit\n", encoding="utf-8")
    assert any("SKILL.md" in d for d in differences(kernel, mirror, generated=False))
    (mirror / "extra.md").write_text("x", encoding="utf-8")
    assert any("extra.md" in d for d in differences(kernel, mirror, generated=False))
