def _without_comments(text):
    """``text`` without ``//`` and ``/* */`` comments and without a comma before ``}`` or ``]``."""
    out, i, in_string = [], 0, False
    while i < len(text):
        char = text[i]
        if in_string:
            out.append(char)
            if char == "\\" and i + 1 < len(text):
                out.append(text[i + 1])
                i += 1
            elif char == '"':
                in_string = False
        elif char == '"':
            in_string = True
            out.append(char)
        elif text.startswith("//", i):
            end = text.find("\n", i)
            i = len(text) if end < 0 else end
            continue
        elif text.startswith("/*", i):
            end = text.find("*/", i + 2)
            i = len(text) if end < 0 else end + 2
            continue
        elif char in "}]":
            while out and out[-1].isspace():
                out.pop()
            if out and out[-1] == ",":
                out.pop()
            out.append(char)
        else:
            out.append(char)
        i += 1
    return "".join(out)


def parse_source(text, name=SOURCE_REL):
    """The object a hooks source holds. A number keeps the kind it was written as (``60`` or ``60.0``)."""
    try:
        data = json.loads(_without_comments(text))
    except ValueError as exc:
        raise AssertionError(f"{name} is not JSON with comments: {exc}") from None
    assert isinstance(data, dict), f"{name} does not hold an object"
    return data


def load_source(path=None, name=SOURCE_REL):
    path = Path(path) if path is not None else REPO_ROOT / SOURCE_REL
    assert path.is_file(), f"{name} does not exist"
    return parse_source(path.read_text(encoding="utf-8"), name)


def write_source(path, source):
    Path(path).write_text(json.dumps(source, indent=2) + "\n", encoding="utf-8")


