"""Helpers for the cases on the template's rulesync hooks source (DEC-596).

DEC-596: the template's rulesync hooks source gets ``"timeout": 60`` on every
guard hook entry, and the entry that runs the containment check after a failed
tool call. A project's harness settings are generated by rulesync from that
source, so what the kernel template's settings carry (DEC-580) reaches an
adopted project only through it.

What the words are taken to mean:

- **A hook entry of the source** is one object of the list an event name holds
  under ``hooks`` (and under ``hooks`` of a block that overrides one tool, if
  the source has such a block): the object that holds ``command``.
- **A guard hook entry**, **carries the limit**: the words of
  ``tests/acceptance/W1-47/w1_47_hook_time_limit.py`` (DEC-592: every hook entry
  that runs a program of the kernel's hooks folder; only the integer 60).
- **The program of an entry** is the file of the kernel's hooks folder its
  command names. The command line around it (how Python is called, how the
  path is written) is not compared.

The generated settings are judged by W1-47's module itself, so the kernel
template's settings (W1-47), a created project's (W1-39) and the generated ones
(here) are held with the same words.
"""

