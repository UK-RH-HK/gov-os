class TestRulesyncPassesBothThrough:
    """A measurement of the registered rulesync, not of the template: the project's copy of the hooks source is
    given the limit on every entry and an entry under rulesync's name for a failed tool call, and the settings
    are generated again. It holds whatever the template's source says, and turns red if a later rulesync drops
    the limit or the event (the source could then not deliver DEC-596 without a hand edit)."""

    @needs_rulesync
    def test_a_limit_and_a_failed_tool_call_entry_of_the_source_reach_the_generated_settings(
        self, project, programs,
    ):
        path = project / hooks.PROJECT_SOURCE_REL
        changed = hooks.load_source(path, hooks.PROJECT_SOURCE_REL)
        after = [entry for where, entry in hooks.source_guard_entries(changed, programs)
                 if where.startswith(f"hooks.{hooks.RULESYNC_AFTER_CALL_KEY}[")]
        assert len(after) == 1, f"the source holds {len(after)} guard hook entries after a tool call; one is expected"
        changed["hooks"][hooks.RULESYNC_FAILED_CALL_KEY] = [{**copy.deepcopy(after[0]), "matcher": "Bash"}]
        for _where, entry in hooks.source_guard_entries(changed, programs):
            entry[limit.LIMIT_KEY] = limit.LIMIT_S
        hooks.write_source(path, changed)
        support.regenerate(project)

        settings = support.load_settings(project)
        assert limit.faults(settings, programs) == [], (
            f"rulesync {support.rulesync_version()} did not carry `{LIMIT}` of every source entry into "
            f"{hooks.GENERATED_REL}: {limit.faults(settings, programs)}"
        )
        program = hooks.program_of(after[0], programs)
        assert hooks.registered(settings, programs, hooks.FAILED_CALL_EVENT) == [("Bash", program, limit.LIMIT_S)], (
            f"rulesync {support.rulesync_version()} did not turn the source's `{hooks.RULESYNC_FAILED_CALL_KEY}` "
            f"entry into a {hooks.FAILED_CALL_EVENT} entry for Bash that runs {program}: "
            f"{json.dumps(settings.get('hooks', {}).get(hooks.FAILED_CALL_EVENT))}"
        )


