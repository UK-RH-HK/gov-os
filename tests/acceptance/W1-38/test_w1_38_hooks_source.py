class TestGeneratedGuardHooks:
    """The settings rulesync generates for Claude Code from the template's source, in a temporary project."""

    @needs_rulesync
    def test_every_guard_hook_entry_of_the_generated_settings_carries_the_time_limit(
        self, generated_settings, programs,
    ):
        """Every generated hook entry that runs a program of the kernel's hooks folder holds the number 60."""
        assert limit.guard_entries(generated_settings, programs), (
            f"{hooks.GENERATED_REL} registers no guard hook entry, so the time limit would be held for nothing"
        )
        found = limit.faults(generated_settings, programs)
        assert not found, (
            f"{hooks.GENERATED_REL}, generated from {hooks.SOURCE_REL}: a guard hook entry without `{LIMIT}` "
            f"(DEC-596):\n  " + "\n  ".join(found)
        )

    @needs_rulesync
    def test_the_generated_settings_run_the_containment_program_after_a_failed_bash_call(
        self, generated_settings, programs,
    ):
        """The harness's event for a failed tool call holds, for Bash, an entry that runs the program the kernel
        template's settings register for it."""
        program = hooks.containment_program(programs)
        commands = hooks.live_support.hook_commands(generated_settings, hooks.FAILED_CALL_EVENT, "Bash")
        assert any(program in command for command in commands), (
            f"{hooks.GENERATED_REL}, generated from {hooks.SOURCE_REL}, registers no {hooks.FAILED_CALL_EVENT} "
            f"command for Bash that runs {program}: it registers {commands}. An adopted project runs no "
            f"containment check after a failed command (DEC-596)"
        )

    @needs_rulesync
    @pytest.mark.parametrize("event", ("PreToolUse", "PostToolUse", "PostToolUseFailure"))
    def test_the_generated_settings_register_what_the_kernel_template_s_settings_register(
        self, generated_settings, programs, event,
    ):
        """Compared, under one event: for every hook entry that runs a kernel hook program, its matcher group's
        matcher (as written, or none), the program, and the value under ``timeout`` -- in the generated settings
        and in ``template/governance/kernel/settings.json``. The command lines around the program are not
        compared."""
        kernel = hooks.registered(hooks.kernel_settings(), programs, event)
        assert kernel, f"{hooks.KERNEL_SETTINGS_REL} registers no guard hook entry under {event}"
        generated = hooks.registered(generated_settings, programs, event)
        assert generated == kernel, (
            f"{event}: {hooks.GENERATED_REL}, generated from {hooks.SOURCE_REL}, registers (matcher, program, "
            f"limit) {generated}; {hooks.KERNEL_SETTINGS_REL} registers {kernel}"
        )

    def test_the_three_events_compared_are_the_kernel_template_s_guard_events(self, programs):
        """The comparison above leaves out no event under which the kernel template registers a guard hook."""
        assert sorted(hooks.guard_events(hooks.kernel_settings(), programs)) == sorted(
            ("PreToolUse", "PostToolUse", "PostToolUseFailure")
        )


