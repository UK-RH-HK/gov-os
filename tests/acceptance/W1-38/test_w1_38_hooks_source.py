# A session's failed command is followed by the containment check
# ===================================================================

class TestFailedCommandInAGeneratedProject:
    """One whole Bash call that fails, as a session makes it, through the commands the generated settings
    register: the PreToolUse commands for Bash, the command for real, then the commands registered for a failed
    tool call, with the input the harness gives then. The engineer works on a ticket whose paths are
    ``src/app/**`` and ``tests/unit/**``."""

    def _call(self, product, sandbox, command, changed):
        call = hooks.failed_bash_call(product, support.load_settings(product), sandbox, command, changed=changed)
        assert call.registered, (
            f"`{command}` failed, and {hooks.GENERATED_REL}, generated from {hooks.SOURCE_REL}, registers no "
            f"{hooks.FAILED_CALL_EVENT} command for Bash: no containment check runs after a failed command "
            f"(DEC-596)"
        )
        assert all(result.returncode == 0 for result in call.results), (
            f"`{command}` failed, and a registered {hooks.FAILED_CALL_EVENT} command did not end cleanly: "
            f"{call.describe()}"
        )
        return call

    @needs_rulesync
    def test_a_change_left_out_of_scope_by_a_failed_command_is_reported_and_recorded(
        self, product, session_sandbox,
    ):
        command = "echo changed >> README.md; exit 3"
        call = self._call(product, session_sandbox, command, ["README.md"])
        assert "README.md" in call.report, (
            f"`{command}` failed after changing README.md outside the ticket's paths, and the agent is not told: "
            f"{call.describe()}"
        )
        findings = [json.loads(line) for line in call.new_findings]
        assert any("README.md" in finding.get("paths", []) for finding in findings), (
            f"`{command}`: no finding for README.md was added to {hooks.check_support.FINDINGS_REL}: {findings}"
        )

    @needs_rulesync
    def test_an_acceptance_test_changed_by_a_failed_command_is_restored(self, product, session_sandbox):
        rel = hooks.ACCEPTANCE_FILE
        before = hooks.check_support.read(product, rel)
        command = f"echo changed >> {rel}; exit 1"
        call = self._call(product, session_sandbox, command, [rel])
        assert hooks.check_support.read(product, rel) == before, (
            f"`{command}` by the engineer failed after changing an acceptance test, and {rel} was not restored: "
            f"{call.describe()}"
        )
        assert rel in call.report, f"`{command}`: the agent is not told that {rel} was restored: {call.describe()}"

    @needs_rulesync
    def test_a_failed_command_that_stays_in_scope_is_left_alone(self, product, session_sandbox):
        rel = hooks.IN_SCOPE_FILE
        command = f"echo changed >> {rel}; exit 1"
        call = self._call(product, session_sandbox, command, [rel])
        assert not call.report and not call.new_findings, (
            f"`{command}` changed only {rel}, inside the ticket's paths, and the check did not stay silent: "
            f"{call.describe()}; findings {call.new_findings}"
        )
        assert rel in hooks.check_support.porcelain_all(product), f"`{command}`: the change to {rel} was undone"
