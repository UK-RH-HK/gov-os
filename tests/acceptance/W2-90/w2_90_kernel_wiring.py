class GenerationFailed(AssertionError):
    """The project could not be generated from the template."""


def generate_project(base, name="product"):
    """A project generated from the template in ``base/<name>``, its ``.claude/`` generated by rulesync, committed.

    The template source and Copier's own home are made under ``base`` and removed once the project exists.
    """
    base = Path(base)
    base.mkdir(parents=True, exist_ok=True)
    copier = copier_support.require_copier()
    source = copier_support.assemble_source(base / "template-source")
    box = copier_support.make_sandbox(base / "copier-sandbox")
    try:
        project, _done = copier_support.create_project_and_run(copier, box, source, base / name)
    finally:
        shutil.rmtree(source.path, ignore_errors=True)
        shutil.rmtree(base / "copier-sandbox", ignore_errors=True)
    generated = rulesync_support.run_rulesync_generate(project)
    if generated.returncode != 0 or not (project / SETTINGS_REL).is_file():
        raise GenerationFailed(f"rulesync generate did not write {SETTINGS_REL} in the generated project "
                               f"(exit {generated.returncode}): {generated.stderr[-1500:]}")
    copier_support.commit_all(project, "rulesync generate: the adapter generation step")
    return project


def load_settings(project):
    """The generated project's ``.claude/settings.json``, parsed."""
    path = Path(project) / SETTINGS_REL
    assert path.is_file(), f"the generated project has no {SETTINGS_REL}"
    data = json.loads(path.read_text(encoding="utf-8"))
    assert isinstance(data, dict), f"the generated {SETTINGS_REL} does not hold a JSON object"
    return data


def load_jsonc(path):
    """A rulesync source (JSON with comments), parsed as W1-38 parses it."""
    import w1_38_hooks_support as hooks_support   # noqa: E402  (imported late: it reaches W1-03 and W1-47)

    return hooks_support.load_source(Path(path), str(path))


def plant(project, files, message):
    """Write ``files`` (relative path: text) into the project and commit them."""
    project = Path(project)
    for rel, text in files.items():
        path = project / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    copier_support.commit_all(project, message)
    return project


def copy_project(base, destination):
    """A copy of a generated project (a temporary folder, never this repository), its git history included."""
    destination = Path(destination)
    shutil.copytree(base, destination, symlinks=True)
    return destination


def install_gov_for(home):
    """Make this worktree's ``gov`` package importable for ``python3`` run with ``HOME=home``.

    A path file in the user site folder of that home, as an editable install leaves one: the kernel's hook line
    starts its program with the ``python3`` first on ``PATH``, and a product has the package installed.
    """
    home = Path(home)
    env = {"PATH": os.environ.get("PATH", "/usr/bin:/bin"), "HOME": str(home), "LC_ALL": "C.UTF-8"}
    site = subprocess.run(["python3", "-c", "import site; print(site.getusersitepackages())"], capture_output=True,
                          text=True, env=env, check=True).stdout.strip()
    assert site.startswith(str(home) + os.sep), f"the user site folder {site} is not under the stand-in home {home}"
    Path(site).mkdir(parents=True, exist_ok=True)
    (Path(site) / PTH_NAME).write_text(str(REPO_ROOT / "src") + "\n", encoding="utf-8")
    return home


