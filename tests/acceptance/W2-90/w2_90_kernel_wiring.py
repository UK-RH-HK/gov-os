"""The kernel's wiring, for the cases W2-90 revised (DEC-957, DEC-953 item 2, DEC-906).

After ACT 1 this repository's own ``.claude/settings.json`` runs a five-rule hook of its own and no containment
hooks. The kernel's guard and its containment hooks stay in the product: ``template/`` (its ``.rulesync/`` sources
and ``governance/kernel/``) and ``src/gov/guard/``. The cases revised by W2-90 assert of that product what they
asserted of this repository's live wiring, with the same verdict.

**A generated project.** The template source is assembled file by file in a temporary folder from ``copier.yml``
and ``template/`` (W1-39's ``assemble_source``: this repository is never Copier's source or destination), a project
is created from it by ``copier copy`` (W1-39's ``create_project_and_run``), and rulesync generates its ``.claude/``
from the project's ``.rulesync/`` (W1-38's ``run_rulesync_generate``): the adapter generation step of the template's
own update procedure. The project's ``.claude/settings.json`` is then the settings a product of the kernel runs
with: the hook lines of ``template/.rulesync/hooks.jsonc`` and the permission rules of
``template/.rulesync/permissions.jsonc``. Its hook programs are at ``governance/kernel/hooks/``, where Copier puts
them. Each suite plants its own fixture files (tickets, a product's files) and commits.

**How a registered line runs.** As Claude Code runs it: through ``sh -c``, the event's JSON on standard input,
``CLAUDE_PROJECT_DIR`` set to the generated project (W1-05's ``run_commands`` and W1-46's ``ask_guard`` do exactly
this). The kernel's line starts its program with the ``python3`` found on ``PATH``; a product has the ``gov``
package installed. Nothing is installed by a test: the package of this worktree is made importable for the stand-in
``HOME`` the way an editable install does it, a path file in that home's user site folder (W1-38's
``make_session_sandbox``). So the hook runs this worktree's ``src/gov`` (DEC-732).
"""

