class GenerationFailed(AssertionError):
    """The project could not be generated from the template."""


def generate_project(base, name="product"):
    """A project generated from the template in ``base/<name>``, its ``.claude/`` generated by rulesync, committed.

    The template source and Copier's own home are made under ``base`` and removed once the project exists.
    """
    base = Path(base)
    base.mkdir(parents=True, exist_ok=True)
    copier = copier_support.require_copier()
    source = copier_support.assemble_source(base / "template-source")
    box = copier_support.make_sandbox(base / "copier-sandbox")
    try:
        project, _done = copier_support.create_project_and_run(copier, box, source, base / name)
    finally:
        shutil.rmtree(source.path, ignore_errors=True)
        shutil.rmtree(base / "copier-sandbox", ignore_errors=True)
    generated = rulesync_support.run_rulesync_generate(project)
    if generated.returncode != 0 or not (project / SETTINGS_REL).is_file():
        raise GenerationFailed(f"rulesync generate did not write {SETTINGS_REL} in the generated project "
                               f"(exit {generated.returncode}): {generated.stderr[-1500:]}")
    copier_support.commit_all(project, "rulesync generate: the adapter generation step")
    return project


def load_settings(project):
    """The generated project's ``.claude/settings.json``, parsed."""
    path = Path(project) / SETTINGS_REL
    assert path.is_file(), f"the generated project has no {SETTINGS_REL}"
    data = json.loads(path.read_text(encoding="utf-8"))
    assert isinstance(data, dict), f"the generated {SETTINGS_REL} does not hold a JSON object"
    return data


