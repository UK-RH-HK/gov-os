def kernel_project(kernel_base, tmp_path):
    """This test's own copy of the project on a generated project."""
    return kernel_wiring.copy_project(kernel_base, tmp_path / "repo")


@pytest.fixture()
def kernel_sandbox(sandbox):
    """This test's sandbox, its home given the editable install's ``gov`` of this worktree."""
    kernel_wiring.install_gov_for(sandbox.home)
    return sandbox


@pytest.fixture()
def kernel_guard(kernel_project, kernel_sandbox):
    """``guard(tool_name, tool_input, role, ticket)``: the generated settings' decision on one call (their deny rules,
    then the PreToolUse lines they register). No call is made."""

    def _guard(tool_name, tool_input, role, ticket=None, cwd=None):
        return launch_support.ask_guard(kernel_project, kernel_sandbox, tool_name, tool_input, role,
                                        ticket or w47.TICKET_OF[role], cwd=cwd)

    return _guard


@pytest.fixture()
def kernel_launch(kernel_project, kernel_sandbox):
    """``launch(role)`` runs ``gov launch <role> <ticket>`` in the project on a generated project, with a stand-in
    CLI that starts no session."""
    directory = w47.make_stand_in(kernel_sandbox.elsewhere / "held-out-stand-in")
    w47.configure_stand_in(kernel_project, directory)
    cli = launch_support.install_stand_in_cli(kernel_sandbox)

    def _launch(role, ticket=None):
        return launch_support.launch(kernel_project, kernel_sandbox, cli, role,
                                     ticket or launch_support.TICKET_OF.get(role) or w47.TICKET_OF[role])

    return _launch


@pytest.mark.parametrize("role", support.ROLES)
def test_only_the_test_designer_may_write_the_acceptance_tests(kernel_guard, kernel_project, role):
    guard, project = kernel_guard, kernel_project
    result = guard("Write", w47.write_input("Write", project / ACCEPTANCE_FILE), role)
    if role == support.TEST_DESIGNER:
        w47.assert_allowed(result, f"a Write to {ACCEPTANCE_FILE} by the test designer")
    else:
        w47.assert_stopped(result, f"a Write to {ACCEPTANCE_FILE} by {role}")


def test_the_orchestrator_may_write_anywhere_else_in_the_repository(kernel_guard, kernel_project):
    guard, project = kernel_guard, kernel_project
    for rel in ("README.md", "src/gov/guard/decide.py", "docs/notes.md", support.ROSTER_REL):
        w47.assert_allowed(guard("Write", w47.write_input("Write", project / rel), support.ORCHESTRATOR),
                           f"a Write to {rel} by the orchestrator")


def test_the_auditor_writes_only_the_report_path_of_its_own_ticket(kernel_guard, kernel_project):
    """DEC-112. The fixture ticket of the auditor allows ``docs/audit/**``."""
    guard, project = kernel_guard, kernel_project
    report = launch_support.OWN_PATH[support.AUDITOR]
    w47.assert_allowed(guard("Write", w47.write_input("Write", project / report), support.AUDITOR),
                       f"a Write to {report} by the auditor on its own ticket")
    for rel in ("README.md", "src/gov/guard/decide.py", "docs/notes.md"):
        w47.assert_stopped(guard("Write", w47.write_input("Write", project / rel), support.AUDITOR),
                           f"a Write to {rel} by the auditor")
    other = guard("Write", w47.write_input("Write", project / report), support.AUDITOR,
                  w47.TICKET_OF[support.ENGINEER])
    w47.assert_stopped(other, f"a Write to {report} by the auditor on an engineer's ticket")


@pytest.mark.parametrize("role", support.ROLES)
def test_an_install_asks_for_the_orchestrator_and_is_denied_to_every_other_role(kernel_guard, role):
    guard = kernel_guard
    result = guard("Bash", w47.bash_input(INSTALL), role)
    if role == support.ORCHESTRATOR:
        assert result.decision == "ask", f"`{INSTALL}` by the orchestrator did not ask: {result.describe()}"
    else:
        w47.assert_stopped(result, f"`{INSTALL}` by {role}")


@pytest.mark.parametrize("role", support.EMPTY_PROFILE_ROLES)
def test_the_launcher_gives_the_role_an_empty_network_profile(kernel_launch, role):
    launch = kernel_launch
    result = launch(role)
    assert launch_support.allowed_domains(result.settings()) == [], (
        f"the settings built for {role} allow hosts: {launch_support.allowed_domains(result.settings())}"
    )


@pytest.mark.parametrize("role", support.NOT_LAUNCHED)
def test_the_launcher_starts_no_session_for_a_role_that_is_not_a_worker(kernel_launch, role):
    launch = kernel_launch
    launch_support.assert_refused(launch(role), "worker role")
