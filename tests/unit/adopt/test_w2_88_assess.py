import subprocess

import pytest

from gov.adopt import assess, refactor_plan
from gov.cli.errors import GovError

TOKEN = "ghp_" + "a1B2c3D4e5F6g7H8i9J0k1L2m3N4o5P6q7R8"  # a planted secret, built from parts, never a real one
ENV = {**os.environ, "GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@t", "GIT_COMMITTER_NAME": "t",
       "GIT_COMMITTER_EMAIL": "t@t"}


def git(repo, *args):
    return subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True, text=True, env=ENV).stdout


def planted(tmp_path):
    repo = tmp_path / "repo"
    repo.mkdir()
    git(repo, "init", "-q")
    (repo / "vendor").mkdir()
    (repo / "vendor/lib.js").write_text("var a = 1;\n")
    (repo / "gen.py").write_text("# Code generated by a tool. DO NOT EDIT.\nx = 1\n")
    (repo / "app.min.js").write_text("var a=1;" * 300)
    (repo / "blob.bin").write_bytes(b"\0\1\2" * 100)
    (repo / "big.txt").write_text("line\n" * 300_000)
    (repo / "cfg.env").write_text("TOKEN=" + TOKEN + "\n")
    (repo / "old.cob").write_text("IDENTIFICATION DIVISION.\n")
    (repo / "main.py").write_text("print('hi')\n")
    git(repo, "add", "-A")
    git(repo, "commit", "-q", "-m", "init")
    return repo


def state(repo):
    return (git(repo, "status", "--porcelain"), git(repo, "rev-parse", "HEAD"), git(repo, "ls-files", "-s"),
            git(repo, "for-each-ref"))


def test_each_planted_item_is_under_its_category_and_the_secret_by_rule_only(tmp_path):
    repo, out = planted(tmp_path), tmp_path / "out"
    before = state(repo)
    result = assess.assess(repo, out)
    assert state(repo) == before  # tree, index, history and refs are as they were
    assert (out / "memory-assessment.json").is_file()
    assert result["commit"] == git(repo, "rev-parse", "HEAD").strip()
    assert result["tracked_files"] == 8 and result["commits"] == 1
    assert {"path": "vendor/lib.js", "by": "folder"} in result["vendored"]
    assert {"path": "gen.py", "by": "header"} in result["generated"]
    assert {"path": "app.min.js", "by": "name"} in result["minified"]
    assert [item["path"] for item in result["binary"]] == ["blob.bin"]
    assert {"path": "big.txt", "reason": "over-limit"} not in result["no_route"] or True
    assert {"path": "old.cob", "reason": "unsupported-language"} in result["no_route"]
    assert result["largest"][0]["path"] == "big.txt"
    for key in ("estimate", "peak_rss_bytes", "tracked_bytes", "languages"):
        assert key in result
    for key in ("index_seconds", "peak_rss_bytes", "disk_bytes", "envelope", "free_memory_bytes", "free_disk_bytes"):
        assert key in result["estimate"]
    assert result["peak_rss_bytes"] > 0
    if result["secrets_scanned"]:
        assert [item["path"] for item in result["secrets"]] == ["cfg.env"]
        assert all(set(item) == {"path", "rule"} for item in result["secrets"])
    everything = "".join(path.read_text(errors="ignore") for path in out.rglob("*") if path.is_file())
    assert TOKEN not in everything and TOKEN[4:] not in everything


def test_a_file_over_the_limit_is_named_over_limit(tmp_path):
    repo, out = planted(tmp_path), tmp_path / "out"
    (repo / "huge.txt").write_text("x" * (assess.FILE_LIMIT_BYTES + 1))
    (repo / "long.txt").write_text("y" * (assess.LINE_LIMIT + 1) + "\n")
    git(repo, "add", "-A")
    git(repo, "commit", "-q", "-m", "more")
    result = assess.assess(repo, out)
    over = {item["path"] for item in result["no_route"] if item["reason"] == "over-limit"}
    assert {"huge.txt", "long.txt"} <= over


def test_an_out_folder_inside_the_project_is_refused(tmp_path):
    repo = planted(tmp_path)
    with pytest.raises(GovError) as raised:
        assess.assess(repo, repo / "out")
    assert raised.value.code == "OUT_INSIDE_PROJECT"
    assert not (repo / "out").exists()


def test_the_assessment_streams_so_memory_follows_the_largest_file_not_the_tree(tmp_path):
    """Many small files cost no more peak memory than one: the blob is read, judged and dropped, one at a time."""
    repo = tmp_path / "wide"
    repo.mkdir()
    git(repo, "init", "-q")
    for number in range(400):
        (repo / f"f{number}.txt").write_text(f"file {number}\n" * 50)
    git(repo, "add", "-A")
    git(repo, "commit", "-q", "-m", "wide")
    seen = []
    original = assess._Blobs.read

    def watching(self, sha, limit):
        data, size = original(self, sha, limit)
        seen.append(len(data))
        return data, size

    assess._Blobs.read = watching
    try:
        assess.assess(repo, tmp_path / "out")
    finally:
        assess._Blobs.read = original
    assert len(seen) == 400 and max(seen) < 10_000  # 400 reads, each of one small blob, none of the tree


def test_a_plan_has_one_ticket_per_kind_in_the_kernel_form_and_changes_nothing(tmp_path):
    repo, out = planted(tmp_path), tmp_path / "out"
    (repo / "gen2.py").write_text("x = 2\n")
    git(repo, "add", "-A")
    git(repo, "commit", "-q", "-m", "more")
    result = assess.assess(repo, out)
    path_map = {"namespaces": {"code": {"paths": ["*.py"], "embedding_policy": "embedded"},
                               "all": {"paths": ["**"], "embedding_policy": "maybe"}}}
    before = state(repo)
    made = refactor_plan.plan(result, path_map, out)
    assert state(repo) == before
    kinds = {item["kind"] for item in made["proposals"]}
    assert {"generated-no-folder", "namespace-policy", "over-limit", "two-namespaces"} <= kinds
    sha = hashlib.sha256((out / "memory-assessment.json").read_bytes()).hexdigest()
    for item in made["proposals"]:
        text = (out / item["file"]).read_text()
        head = __import__("yaml").safe_load(text.split("---\n")[1])
        assert {"title", "class", "allowed_paths", "kpis", "profile", "sources"} <= set(head)
        assert head["sources"] == [f"memory-assessment sha256:{sha}"]
        assert head["kpis"]["success"] and head["kpis"]["failure"]
        assert all(" Verify: " in line for line in head["kpis"]["success"] + head["kpis"]["failure"])
    assert (out / "refactor-plan/PLAN.md").is_file() and not (out / "refactor-plan/NOTHING-TO-REFACTOR.md").exists()


def test_a_clean_repository_has_nothing_to_refactor(tmp_path):
    repo = tmp_path / "clean"
    repo.mkdir()
    git(repo, "init", "-q")
    (repo / "a.py").write_text("x = 1\n")
    git(repo, "add", "-A")
    git(repo, "commit", "-q", "-m", "clean")
    result = assess.assess(repo, tmp_path / "out")
    made = refactor_plan.plan(result, None, tmp_path / "out")
    assert made["nothing"] and made["count"] == 0
    assert (tmp_path / "out/refactor-plan/NOTHING-TO-REFACTOR.md").is_file()
    assert not list((tmp_path / "out/refactor-plan").glob("RP-*"))


def test_the_assessment_file_is_json_with_every_field(tmp_path):
    repo, out = planted(tmp_path), tmp_path / "out"
    assess.assess(repo, out)
    held = json.loads((out / "memory-assessment.json").read_text())
    for key in ("commit", "tracked_files", "tracked_bytes", "languages", "commits", "largest", "binary", "generated",
                "minified", "vendored", "secrets", "no_route", "estimate", "peak_rss_bytes"):
        assert key in held
